DEFAULT_RELATIVE_RMS_ERROR_LIMIT = 0.10
MAX_MIN_RELATIVE_RMS_ERROR_LIMIT = 0.20


def validate_series_length(
    n: int,
    min_probability: float | None = None,
    relative_rms_error: float | None = None,
    error_limit: float = DEFAULT_RELATIVE_RMS_ERROR_LIMIT,
) -> list[str]:
    """Проверить достаточность ряда по критерию СП 33-101-2003 п. 5.1.

    ``min_probability`` сохранён для совместимости с прежним API и больше не
    определяет фиксированное число лет наблюдений.
    """
    if relative_rms_error is None:
        return [
            f"⚠️ СП 33-101-2003 п. 5.1: для ряда n={n} необходимо проверить "
            f"относительную среднеквадратическую погрешность"
        ]

    # Отдельно от «превышает предел»: бесконечность означает, что погрешность
    # вообще не вычислилась, потому что нормативное r(1) по (Б.1) оказалось
    # не меньше единицы и множитель в (5.26)/(5.27) не имеет вещественного
    # значения. Сообщать «inf% превышает предел» значило бы утверждать, что
    # превышение измерено.
    if not np.isfinite(relative_rms_error):
        return [
            f"⚠️ СП 33-101-2003 п. 5.1: относительная среднеквадратическая "
            f"погрешность среднего НЕ ВЫЧИСЛЕНА для ряда n={n}: нормативное "
            f"r(1) по (Б.1) не меньше единицы, множитель в (5.26)/(5.27) "
            f"не имеет вещественного значения. Предел {error_limit * 100:.0f}% "
            f"не проверен"
        ]

    if relative_rms_error > error_limit:
        return [
            f"⚠️ СП 33-101-2003 п. 5.1: относительная среднеквадратическая "
            f"погрешность {relative_rms_error * 100:.1f}% превышает предел "
            f"{error_limit * 100:.0f}% для ряда n={n}"
        ]

    return []


def relative_mean_error_percent(
    cv: float,
    n: int,
    lag1_autocorrelation: float,
) -> float:
    """Рассчитать погрешность среднего по формулам СП 33 п. 5.26–5.27.

    Для ``r < 0.5`` применяется формула 5.26, для ``r >= 0.5`` — более
    точная формула 5.27. Результат возвращается в процентах.

    ВАЖНО, что такое ``lag1_autocorrelation``. Стандарт в (5.26)-(5.27) требует
    нормативное r(1) по (Б.1)-(Б.3) приложения Б, а не корреляцию Пирсона: в
    (Б.2) используются две разные средние, и оценка затем приводится к
    несмещённой через (Б.1). Величины различаются.

    ВОЗВРАТ inf — ЭТО «НЕ ВЫЧИСЛЕНО», А НЕ «БЕСКОНЕЧНО БОЛЬШОЕ ЗНАЧЕНИЕ».
    Обе формулы содержат множитель, знаменатель которого обращается в ноль при
    r → 1, поэтому при r >= 1 вещественного значения не существует. На практике
    это короткие ряды: при n = 8 и r̃ = 0,566 нормативное r(1) = 1,418, и
    (5.26)/(5.27) к такому ряду неприменимы. Молча подставлять вместо r(1)
    корреляцию Пирсона здесь нельзя — получилось бы завышенное впечатление о
    применимости методики. Вызывающий код обязан трактовать inf как
    неприменимость, а ``validate_series_length`` сообщает об этом прямо.
    """
    if n < 2:
        raise ValueError("Для погрешности среднего нужно минимум 2 наблюдения")
    if not np.isfinite(cv) or cv < 0.0:
        raise ValueError("Cv должен быть конечным и неотрицательным")
    if cv == 0.0:
        return 0.0

    r = float(lag1_autocorrelation)
    if not np.isfinite(r) or abs(r) >= 1.0:
        return float("inf")

    if r < 0.5:
        factor = np.sqrt((1.0 + r) / (1.0 - r))
    else:
        correction = sum(1.0 - r**power for power in range(1, n))
        numerator = 1.0 + 2.0 * r / (n * (1.0 - r)) * correction
        denominator = 1.0 - 2.0 * r / (
            n * (n - 1) * (1.0 - r)
        ) * correction
        if denominator <= 0.0:
            return float("inf")
        factor = np.sqrt(numerator / denominator)

    return float(cv / np.sqrt(n) * factor * 100.0)


