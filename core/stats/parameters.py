def sp33_autocorrelation_b1_b2_b3(series: np.ndarray) -> dict:
    """Коэффициент автокорреляции по (Б.1)-(Б.3) СП 33-101-2003, приложение Б.

        (Б.3)  Q̄₁ = Σ(i=2..n) Qᵢ / (n-1);   Q̄₂ = Σ(i=2..n-1) Qᵢ / (n-1)
        (Б.2)  r̃(1) = Σ(Qᵢ - Q̄₁)(Qᵢ₋₁ - Q̄₂) / √[Σ(Qᵢ - Q̄₁)² · Σ(Qᵢ₋₁ - Q̄₂)²]
        (Б.1)  r(1) = -0,01 + 0,98·r̃ - 0,06·r̃² + (1,66 + 6,46·r̃ + 5,69·r̃²)/n

    Это НЕ обычная корреляция Пирсона первого порядка: стандарт использует две
    разные средние, Q̄₁ по i = 2..n и Q̄₂ по i = 2..n-1, и только затем приводит
    смещённую оценку r̃ к несмещённой через (Б.1).

    Источник: печатный экземпляр, стр. 74, снимок `Б1.png` от 2026-09-29.
    Знаменатель в (Б.1) — именно n, простая дробь 1/n. Ранее здесь стоял √n:
    это была ошибочная транскрипция по текстовому слою PDF, где дробь 1/n
    не читается. Расхождение было поймано только на снимке печати.

    ВНИМАНИЕ, особенность оригинала. В (Б.3) знаменатель у Q̄₁ и у Q̄₂ один и
    тот же — (n-1), хотя сумма при Q̄₂ берётся по n-2 членам (i = 2..n-1).
    Это воспроизведено буквально, как напечатано; «исправлять» на n-2 оснований
    нет, и расхождение зафиксировано тестом.

    Returns:
        r(1), смещённая оценка r̃(1) и обе средние.
    """
    x = np.asarray(series, dtype=float)
    n = x.size
    if n < 3:
        raise ValueError("Для (Б.1)-(Б.3) нужно минимум 3 наблюдения")

    q_bar_1 = float(np.sum(x[1:]) / (n - 1))       # i = 2..n
    q_bar_2 = float(np.sum(x[1:n - 1]) / (n - 1))   # i = 2..n-1, знаменатель как в печати

    a = x[1:] - q_bar_1
    b = x[:-1] - q_bar_2
    denominator = float(np.sqrt(np.sum(a**2) * np.sum(b**2)))
    if denominator == 0.0:
        raise ValueError("Ряд без изменений: (Б.2) не определён")
    r_tilde = float(np.sum(a * b) / denominator)

    # (Б.1) — знаменатель именно n (дробь 1/n), а не корень из n.
    r1 = (
        -0.01
        + 0.98 * r_tilde
        - 0.06 * r_tilde**2
        + (1.66 + 6.46 * r_tilde + 5.69 * r_tilde**2) / n
    )
    return {
        "r1": float(r1),
        "r_tilde": r_tilde,
        "q_bar_1": q_bar_1,
        "q_bar_2": q_bar_2,
        "n": n,
    }


def sp33_lag1_autocorrelation(series) -> dict:
    """Единая точка получения r(1) по (Б.1)-(Б.3) для всех потребителей.

    Зачем помощник. (5.26), (5.27), (5.6) и (5.7) СП 33 требуют нормативное
    r(1) из приложения Б, а не корреляцию Пирсона. В (Б.2) используются две
    разные средние, Q̄₁ и Q̄₂, и смещённая оценка r̃ приводится к несмещённой
    через (Б.1). Величины различаются, и подмена одной другой повторяла бы
    ровно тот дефект, который закрыт в (Б.1) и (7.51).

    Раньше нормативное r(1) подставлялось только в calculate_statistical_parameters,
    а max_runoff и compute_basic_stats брали np.corrcoef. Три вызывающих места,
    два из которых считали по другой величине, чем требовал стандарт, — это
    расхождение, поэтому источник r(1) определён здесь один раз.

    Returns:
        r1 — нормативное r(1); r_tilde — смещённая оценка (Б.2), либо None;
        pearson — корреляция Пирсона первого порядка, всегда считается и
        возвращается наружу, чтобы её нельзя было выдать за нормативную;
        source — откуда взято r(1), строкой;
        normative — True, если применено (Б.1)-(Б.3);
        error — причина отказа, когда (Б.1)-(Б.3) неприменимы.
    """
    x = np.asarray(series, dtype=float)
    pearson = float(np.corrcoef(x[:-1], x[1:])[0, 1]) if x.size > 1 else 0.0
    try:
        b1 = sp33_autocorrelation_b1_b2_b3(x)
    except ValueError as exc:
        return {
            "r1": pearson,
            "r_tilde": None,
            "pearson": pearson,
            "normative": False,
            "error": str(exc),
            "source": f"корреляция Пирсона: (Б.1)-(Б.3) неприменимы к ряду ({exc})",
        }
    return {
        "r1": b1["r1"],
        "r_tilde": b1["r_tilde"],
        "pearson": pearson,
        "normative": True,
        "error": None,
        "source": "СП 33-101-2003, приложение Б, формулы (Б.1)-(Б.3)",
    }


def _nearest_node(value: float, nodes) -> float:
    """Ближайший узел таблицы; при равенстве расстояний берётся нижний.

    Интерполяция по (5.6), (5.7) стандартом НЕ предписана, поэтому она не
    вводится: используется прямой выбор строки таблицы, а выбранные узлы
    возвращаются наружу, чтобы решение можно было проверить по первоисточнику.
    """
    return min(nodes, key=lambda node: (abs(value - node), node))


