def get_ordinates(cs_cv: float, cv: float):
    """
    Возвращает ординаты Крицкого-Менкеля для заданных Cs/Cv и Cv
    с помощью билинейной интерполяции по таблицам.
    """
    available_cs = sorted(TABLES.keys())
    
    # Находим два ближайших Cs/Cv
    if cs_cv <= available_cs[0]:
        cs1 = cs2 = available_cs[0]
    elif cs_cv >= available_cs[-1]:
        cs1 = cs2 = available_cs[-1]
    else:
        for i in range(len(available_cs) - 1):
            if available_cs[i] <= cs_cv <= available_cs[i + 1]:
                cs1 = available_cs[i]
                cs2 = available_cs[i + 1]
                break
    
    def interpolate_for_cs(cs_val, cv_val):
        cv_dict = TABLES[cs_val]
        available_cv = sorted(cv_dict.keys())
        
        if cv_val <= available_cv[0]:
            return np.array(cv_dict[available_cv[0]])
        if cv_val >= available_cv[-1]:
            return np.array(cv_dict[available_cv[-1]])
        
        for i in range(len(available_cv) - 1):
            if available_cv[i] <= cv_val <= available_cv[i + 1]:
                cv_low = available_cv[i]
                cv_high = available_cv[i + 1]
                break
        
        y_low = np.array(cv_dict[cv_low])
        y_high = np.array(cv_dict[cv_high])
        
        t = (cv_val - cv_low) / (cv_high - cv_low)
        return y_low * (1 - t) + y_high * t
    
    y1 = interpolate_for_cs(cs1, cv)
    y2 = interpolate_for_cs(cs2, cv)
    
    if cs1 == cs2:
        return y1
    
    t = (cs_cv - cs1) / (cs2 - cs1)
    return y1 * (1 - t) + y2 * t