# УНИВЕРСАЛЬНАЯ ФУНКЦИЯ
# ============================================================

def get_critical_value(test_name: str, n: int, alpha: float = 0.05, cs: float = 0.0):
    if test_name == "dixon":
        return get_dixon_critical(n, alpha, cs)
    elif test_name == "grubbs":
        return get_grubbs_critical(n, alpha, cs)
    return None