def _cs_category(cs: float) -> str:
    if cs < 0.5:
        return 'low'
    elif cs < 1.5:
        return 'med'
    else:
        return 'high'


def get_dixon_critical(n: int, alpha: float = 0.05, cs: float = 0.0) -> Optional[float]:
    """Критическое значение теста Диксона с учётом Cs."""
    if alpha not in [0.01, 0.05]:
        alpha = 0.05

    cat = _cs_category(cs)

    if n in DIXON_TABLE and cat in DIXON_TABLE[n]:
        return DIXON_TABLE[n][cat].get(alpha)

    # Интерполяция
    ns = sorted(DIXON_TABLE.keys())
    for i in range(len(ns)-1):
        if ns[i] < n < ns[i+1]:
            v1 = DIXON_TABLE[ns[i]][cat].get(alpha, 0)
            v2 = DIXON_TABLE[ns[i+1]][cat].get(alpha, 0)
            return np.interp(n, [ns[i], ns[i+1]], [v1, v2])

    if n > 30:
        return 0.18 if alpha == 0.05 else 0.24
    return None


