"""
core/hydrorash/min_runoff_extended.py
Расширенный модуль расчёта минимальных стоков

Реализация расчётов 7-суточных, 10-суточных и 30-суточных минимумов,
экосистемного минимума.

СТАТУС НОРМАТИВНОЙ ПРИВЯЗКИ. Действующая нормативная область минимального
стока — СП 529.1325800.2023, раздел 5.5 «Минимальный сток воды рек». Модуль
реализует лишь часть этой области; соответствие модуля требованиям
СП 529.1325800.2023 в целом НЕ УСТАНОВЛЕНО.

Что установлено сверкой по локальному экземпляру СП 529.1325800.2023:

- п. 5.5.1 (стр. 30) — расчёт минимальных расходов при наличии данных
  наблюдений достаточной продолжительности проводят по кривым обеспеченности
  (см. 5.1.3). Для расчётов используют минимальные среднесуточные,
  среднемесячные или 30-суточные (некалендарные) расходы воды, наблюдавшиеся
  в зимний и (или) летне-осенний сезоны. В районах с частыми паводками могут
  быть расчётными минимальные средние расходы воды за 5 и 10 сут.
- п. 5.5.2 (стр. 30) — при значительных расхождениях аналитической кривой и
  фактических данных в нижней части применяют эмпирические кривые
  обеспеченности; характерный изгиб приходится на зону 90 % – 97 %.
- п. 5.5.3 (стр. 30) — при наличии нулевых расходов расчёты проводят в
  соответствии с п. 5.1.11 (составные кривые распределения).
- п. 7.8.2 – 7.8.5 (стр. 56) — отдельная нормативная ветка: минимальный сток
  больших и средних рек по данным наблюдений (7.8.2) и минимальный сток
  неизученных малых равнинных и полугорных рек по формулам (7.41) и (7.42)
  с ограничениями области применения по 7.8.5.

ФОРМУЛЫ (7.41) И (7.42) В ЭТОМ МОДУЛЕ НЕ РЕАЛИЗОВАНЫ:

- (7.41) Qp% = b(A − A1)^m · λp% — зависимость минимального расхода от
  площади водосбора для малых рек. Параметры b, m, A1 и λp% определяются по
  рекам-аналогам; площадь водосбора в модуле не используется.
- (7.42) Qсут p% = k · Q80% · λp% — минимальный среднесуточный расход через
  районный коэффициент k. Ни k, ни Q80%, ни λp% в модуле не используются.
- Ограничения области применения по 7.8.5 (относительная озерность водосборов
  менее 2 %, заболоченность менее 5 %, отсутствие карста и многолетней
  мерзлоты) в модуле не проверяются.
- Региональные коэффициенты и коэффициенты по рекам-аналогам в модуле
  отсутствуют.

НЕ РЕАЛИЗОВАНО по п. 5.5.1 – 5.5.3: усечённые (5.3.4) и составные (5.1.11)
кривые распределения; среднемесячный минимум; правило выбора типа минимума;
5-суточные минимумы; эмпирические кривые обеспеченности при изгибе
90 % – 97 %.

ЭКОСИСТЕМНЫЙ МИНИМУМ. Понятия «экологический (экосистемный) минимум»,
«санитарный расход» и «попуск» в СП 529.1325800.2023 не встречаются ни разу.
Показатель 7Q10 в документе также не обнаружен: п. 5.5.1 перечисляет 5- и
10-суточные минимумы, а не 7-суточный. Соответствие этих методов СП 529 не
установлено; в проверенном СП 529 и в историческом СП 33-101-2003 источник для
них не верифицирован в рамках текущего аудита.

ИСТОРИЧЕСКАЯ АТРИБУЦИЯ: СП 33-101-2003, п. 5.41–5.43. Первоисточник присутствует
в локальной нормативной базе: DOCS/NORMATIVE/HISTORICAL/СП 33-101-2003.pdf.
Сверка 2026-09-30 по этому файлу (стр. 13) подтвердила содержание всех трёх
пунктов:

- п. 5.41 — расчёт минимальных расходов по кривым обеспеченности; при
  неоднородности ряда применяются усечённые (см. 5.29) или составные
  (см. 5.12) кривые; при значительных расхождениях в нижней части —
  эмпирические кривые вероятностей превышения;
- п. 5.42 — «Для расчётов используют минимальные среднесуточные, среднемесячные
  или 30-суточные (некалендарные) расходы воды, наблюдавшиеся в зимний и (или)
  летне-осенний сезоны»; действует правило 10 % из п. 5.42 — среднемесячные
  применяются, только если не превышают 30-суточные более чем на 10 %; при
  частых паводках 30-суточный период допускается сокращать до 24 сут;
- п. 5.43 — минимальный среднемесячный (календарный) расход рекомендуется для
  рек восточнее границы «Ладожское озеро — верховья рек Днепра и Оки — среднее
  течение Дона — устье Волги» либо южнее границы «Санкт-Петербург — Пермь —
  Магнитогорск — Тюмень — Новосибирск — Барнаул», исключая реки Северного
  Кавказа; для остальных районов — 30-суточные (некалендарные).

Следовательно, прежняя атрибуция на п. 5.41–5.43 была корректной по
существу: эти пункты СП 33 действительно посвящены минимальному стоку. Она
остаётся исторической, поскольку действующий документ проекта — СП
529.1325800.2023, а номера пунктов СП 33 на СП 529 не переносятся: в СП 529
минимальный сток регулирует раздел 5.5, а не раздел 5. Прежняя ссылка
«СП 32.13330.2018» также ошибочна — по официальным метаданным это
«Канализация. Наружные сети и сооружения», другой предмет.

Нереализованные положения п. 5.41–5.43, 5.42 (усечённые и составные кривые,
нулевые расходы, эмпирические кривые, правило выбора типа минимума, сокращение
до 24 сут, региональное ограничение) в модуле по-прежнему отсутствуют.

ВНИМАНИЕ при чтении кода: вхождения «10 %» и «0,1» в этом модуле относятся к
ЭКОЛОГИЧЕСКОМУ нормативу 0,1·Qср. Это самостоятельная инженерная величина;
источник для неё в проверенном СП 529 и в историческом СП 33 не верифицирован
в рамках текущего аудита.

"""


import numpy as np
import pandas as pd

