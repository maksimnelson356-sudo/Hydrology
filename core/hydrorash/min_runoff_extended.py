# Типы индекса, которые несут календарную дату. inferred_type — собственная
# классификация pandas: 'datetime64' (DatetimeIndex), 'period' (PeriodIndex),
# 'datetime' (object-индекс из Timestamp), 'date' (object-индекс из date).
# Строки, числа и смешанные значения ('string', 'integer', 'mixed') сюда не
# попадают, поэтому неоднозначный вход молча не приводится к дате.
_CALENDAR_INFERRED_TYPES = frozenset({"datetime64", "period", "datetime", "date"})


def _calendar_order_key(index: pd.Index) -> np.ndarray | None:
    """Хронологический ключ по полной календарной дате.

    Единая временная шкала для упорядочивания строк перед построением окна,
    независимо от конкретного типа индекса. None — индекс календарную дату не
    несёт, и порядок суток восстановить нельзя.

    PeriodIndex приводится к началу своего периода: при суточной частоте это
    точная дата, при месячной все дни месяца дают одну отметку, и порядок
    внутри месяца сохраняется устойчивой сортировкой.
    """
    if getattr(index, "inferred_type", None) not in _CALENDAR_INFERRED_TYPES:
        return None
    try:
        if isinstance(index, pd.PeriodIndex):
            return index.to_timestamp().to_numpy()
        return pd.DatetimeIndex(index).to_numpy()
    except (ValueError, TypeError):
        return None


def extract_min_annual(
    daily_df: pd.DataFrame,
    year_col: str = 'year',
    value_col: str = 'value',
    period_days: int = 7,
    season: str = "winter"
) -> pd.Series:
    """
    Извлечение средних минимальных расходов за period_days суток для каждого года.

    Использует скользящее окно минимального среднего значения.

    Функция извлекает минимальные средние расходы за скользящий НЕКАЛЕНДАРНЫЙ
    период: окно не привязано к календарным датам, а перебирается по всем
    положениям внутри расчётного цикла (или сезона).

    РАСЧЁТНЫЙ ЦИКЛ. Некалендарное окно не должно обрываться на границе
    31 декабря, поэтому для season="winter"/"summer" при наличии сведений о
    месяце данные группируются расчётным циклом 1 апреля — 31 марта, а окно
    ищется по непрерывному сезонному массиву внутри цикла. Метка цикла — год
    его окончания.

    НОРМАТИВНОЕ ОСНОВАНИЕ — только требование, а не дата. «Пособие по
    определению расчётных гидрологических характеристик», Л.: Гидрометеоиздат,
    1984, п. 2.33, с. 31: 30-суточные некалендарные расходы фиксируются
    «независимо от привязки этих 30-суточных периодов к календарному году»,
    и расчёт производится «за каждый год наблюдений» — то есть одно значение
    на год. Пункт 2.33 НЕ устанавливает дату начала расчётного цикла.

    ГРАНИЦА ЦИКЛА — ИНЖЕНЕРНАЯ КОНВЕНЦИЯ, НЕ НОРМАТИВНАЯ. Источник не задаёт
    универсальную дату начала такого цикла: Пособие 1984, с. 32, показывает
    региональную зависимость начала водохозяйственного года — 1 апреля для
    большей части северо-запада ЕТР и 1 мая в Восточной Сибири. Функция не
    получает региональный (водохозяйственный) район, поэтому 1 апреля взято
    как внутренняя конвенция; выбрана она вне текущего winter_months =
    [11, 12, 1, 2, 3], чтобы холодный сезон не разрывался. Численная проверка
    показала эквивалентность границ с 1 апреля по 1 октября для этого
    winter-алгоритма: значения и метки идентичны, поскольку все месяцы
    XI-III лежат вне интервала April..October. Смена месяца границы влияет
    только на метку и не может изменить вычисленный минимум.

    ТАБЛИЦА 68 (с. 107) приводится только как пример ФОРМЫ представления
    зимнего расчёта: «Осень» = X, XI, XII, «Зима» = I, II, III и обозначения
    лет вида 1897-98. Начало расчётного цикла в таблице явно не задано, и
    такие обозначения совместимы как с циклом X-IX, так и с циклом IV-III,
    поэтому таблица не может обосновать выбранную границу.

    ЛЕТНЕ-ОСЕННИЙ СЕЗОН. Нормативные источники называют второй сезон
    «летне-осенним», а не «летним»: Пособие 1984, п. 2.33, с. 31 — «для зимнего
    и летне-осеннего сезонов»; СП 529.1325800.2023, п. 5.5.1 — «в зимний и (или)
    летне-осенний сезоны»; СП 33-101-2003, п. 5.42 (исторический источник, на
    СП 529 не переносится) — то же. Поэтому summer_months = [6, 7, 8, 9, 10]:
    сентябрь и октябрь входят в сезон, а при составе VI-VIII были недостижимы,
    и минимум осенней межени мог быть пропущен. VI-X идут подряд внутри
    расчётного цикла 1 апреля — 31 марта, поэтому окно остаётся непрерывным
    и требование Q2 о неразрывности не нарушается.

    Границы сезона источниками заданы ФИЗИЧЕСКИ (от конца половодья до начала
    ледовых явлений), а не набором месяцев, поэтому состав VI-X — календарная
    аппроксимация той же природы, что и нерешённый вопрос Q1 по зимним
    месяцам; Q1 настоящим исправлением не закрывается.

    ИНДЕКС РЕЗУЛЬТАТА. Для season="annual" и при отсутствии сведений о месяце
    индекс остаётся календарным годом. Для season="winter"/"summer" при
    наличии сведений о месяце индекс — метка расчётного цикла: 2001 означает
    цикл апрель 2000 — март 2001. Циклы с неполным сезоном на краях ряда
    отбрасываются и значения не дают.

    НЕ РЕШЕНО (Q1). Состав winter_months = [11, 12, 1, 2, 3] остаётся текущей
    инженерной аппроксимацией и настоящей правкой не является. П. 2.33 задаёт
    зимний период физически — от начала ледовых явлений до начала весеннего
    половодья; переход к этим датам здесь не выполняется и требует отдельного
    решения владельца методики.

    НОРМАТИВНЫЙ СТАТУС: ЧАСТИЧНОЕ ПРЕДМЕТНОЕ СООТВЕТСТВИЕ
    СП 529.1325800.2023, п. 5.5.1. Норма допускает использование минимальных
    среднесуточных, среднемесячных или 30-суточных (некалендарных) расходов,
    наблюдавшихся в зимний и (или) летне-осенний сезоны, — некалендарный
    характер периода и сезонный выбор в этой функции присутствуют.

    Однако реализованные здесь окна 7/10/30 суток и состав сезонов НЕ являются
    буквальной реализацией всей нормы: п. 5.5.1 перечисляет также минимальные
    среднесуточные и среднемесячные расходы, а в районах с частыми паводками
    допускает 5- и 10-суточные минимумы. Среднемесячный минимум, 5-суточный
    вариант, усечённые (5.3.4) и составные (5.1.11) кривые распределения в этой
    функции НЕ РЕАЛИЗОВАНЫ. Полная нормативная реализация п. 5.5 не заявляется.

    Parameters:
        daily_df: DataFrame с суточными расходами (должен содержать year_col и value_col)
        year_col: название столбца с годами
        value_col: название столбца с расходами
        period_days: длительность периода (7 или 10 суток)
        season: сезон поиска минимума:
            - "winter" — зимний период (XII–II или XI–III)
            - "summer" — летне-осенний период (VI–X)
            - "annual" — весь год

    Returns:
        Series с минимальными средними расходами, индексированная по годам
    """
    if year_col not in daily_df.columns or value_col not in daily_df.columns:
        raise ValueError(f"DataFrame должен содержать столбцы '{year_col}' и '{value_col}'")

    if period_days not in (7, 10, 30):
        raise ValueError("Допустимые значения period_days: 7, 10, 30")

    df = daily_df[[year_col, value_col]].copy()
    df = df.dropna(subset=[value_col])
    df[value_col] = pd.to_numeric(df[value_col], errors='coerce')
    df = df.dropna(subset=[value_col])

    if len(df) == 0:
        return pd.Series(dtype=float)

    winter_months = [11, 12, 1, 2, 3]
    summer_months = [6, 7, 8, 9, 10]

    if 'month' in daily_df.columns:
        # Выше df сведён к [year_col, value_col], поэтому колонку 'month' нужно
        # брать из daily_df. Проверка по df давала False всегда:season молча
        # вырождался в годовой минимум, а колонка месяца, переданная вызывающим,
        # молча игнорировалась.
        df = df.copy()
        df['month'] = daily_df.loc[df.index, 'month']
        month_col = 'month'
    elif hasattr(df.index, 'month'):
        df = df.copy()
        df['month'] = df.index.month
        month_col = 'month'
    elif hasattr(daily_df.index, 'month'):
        df = df.copy()
        df['month'] = daily_df.loc[df.index].month
        month_col = 'month'
    elif _calendar_order_key(daily_df.index) is not None:
        # Тот же календарный путь, что и в _calendar_order_key: индекс уже
        # признан несущим календарную дату, поэтому месяц берётся из временной
        # шкалы. Нужно для object-индексов из Timestamp и из datetime.date —
        # у них нет собственного .month, хотя календарь они несут.
        df = df.copy()
        if isinstance(daily_df.index, pd.PeriodIndex):
            df['month'] = daily_df.index.to_timestamp().month.to_numpy()
        else:
            df['month'] = pd.DatetimeIndex(daily_df.index).month.to_numpy()
        month_col = 'month'
    else:
        month_col = None

    if season in ("winter", "summer") and month_col is None:
        # Молчаливый переход сезонного расчёта к годовому минимуму запрещён:
        # результат подписывался бы «30-суточные зимние минимумы», хотя был
        # посчитан по всему году. production-путь handle_min_runoff передаёт
        # daily_df из GUI, где календарь не гарантирован, поэтому отсутствие
        # календаря обязано быть явной ошибкой, а не искажённым числом.
        raise ValueError(
            f"season={season!r} требует сведений о месяце, а они не найдены. "
            f"Нужен столбец 'month' в DataFrame либо индекс-дата "
            f"(DatetimeIndex/PeriodIndex). Без них сезон определить нельзя: "
            f"расчёт молча выродился бы в годовой минимум. "
            f"Для расчёта за весь год укажите season='annual'."
        )

    # Q2 (пособие 1984, п. 2.33, с. 31): некалендарное N-суточное окно не
    # привязано к календарному году, поэтому в seasonal-режиме при доступном
    # month данные группируются расчётным циклом 1 апреля — 31 марта, и окно
    # ищется по НЕПРЕРЫВНОМУ сезонному массиву внутри цикла. Метка цикла —
    # год его окончания: Apr-Dec 2000 и Jan-Mar 2001 дают цикл 2001.
    # Режимы season="annual" и month_col is None сохраняют календарную
    # группировку без изменений.
    interannual = False
    group_col = year_col
    required_months = None

    if season in ("winter", "summer") and month_col is not None:
        years_num = pd.to_numeric(df[year_col], errors='coerce')
        months_num = pd.to_numeric(df[month_col], errors='coerce')
        if years_num.notna().all() and months_num.notna().all():
            df['_cycle_year'] = (
                years_num.astype('int64') + (months_num >= 4).astype('int64')
            )
            group_col = '_cycle_year'
            interannual = True
            required_months = winter_months if season == "winter" else summer_months

    results = {}

    for label in df[group_col].unique():
        group_data = df[df[group_col] == label]

        if interannual:
            # Неполный сезон на краю ряда значения не даёт.
            present = set(pd.unique(group_data[month_col]))
            if not set(required_months).issubset(present):
                continue

        year_data = group_data.copy()

        if month_col is not None and month_col in year_data.columns:
            if season == "winter":
                year_data = year_data[year_data[month_col].isin(winter_months)]
            elif season == "summer":
                year_data = year_data[year_data[month_col].isin(summer_months)]

        if len(year_data) < period_days:
            continue

        # Порядок строк обязан быть хронологическим: окно скользящее и строится
        # по соседним строкам (np.convolve), поэтому перестановка входа меняла
        # найденное окно при неизменном наборе суток. Ключ сортировки — полная
        # календарная дата, если индекс её несёт (DatetimeIndex, PeriodIndex,
        # object-индекс из дат); это сохраняет переход через 31 декабря.
        # Если даты нет, остаётся позиция месяца внутри цикла апр–мар
        # (апрель = 0 … март = 11) — этого достаточно, чтобы установить порядок
        # месяцев, но не суток внутри них. Сортировка устойчивая; исходный
        # DataFrame вызывающего не изменяется.
        order_key = _calendar_order_key(year_data.index)
        if order_key is not None:
            year_data = year_data.iloc[np.argsort(order_key, kind="stable")]
        elif month_col is not None:
            month_pos = (pd.to_numeric(year_data[month_col]).to_numpy() - 4) % 12
            year_data = year_data.iloc[np.argsort(month_pos, kind="stable")]

        values = year_data[value_col].values
        min_avg = _sliding_window_min_mean(values, period_days)
        if min_avg is not None:
            results[label] = min_avg

    return pd.Series(results, dtype=float).sort_index()


def _sliding_window_min_mean(
    values: np.ndarray,
    window_size: int
) -> float | None:
    """
    Поиск минимального среднего значения в скользящем окне.

    Parameters:
        values: массив значений расходов
        window_size: размер окна (7, 10 или 30)

    Returns:
        Минимальное среднее значение или None
    """
    if len(values) < window_size:
        return None

    window_sums = np.convolve(values, np.ones(window_size), mode='valid')
    window_means = window_sums / window_size
    idx_min = np.argmin(window_means)
    min_mean = float(window_means[idx_min])

    return min_mean


def compute_min_runoff_stats(
    min_series: pd.Series,
    period_days: int = 7,
    use_normative_Cs: bool = True
) -> dict:
    """Статистическая обработка ряда минимальных расходов.

    НОРМАТИВНЫЙ СТАТУС. Функция выполняет статистическую обработку готового
    ряда минимальных расходов (среднее, коэффициенты изменчивости и асимметрии,
    Cs/Cv, погрешность). Нормативная методика формирования статистических
    параметров ряда определяется общими разделами 5.1 и 5.2 СП 529.1325800.2023;
    настоящая функция не является доказанной полной реализацией
    соответствующего нормативного алгоритма. Соответствие НЕ УСТАНОВЛЕНО.
    """
    series = min_series.dropna()

    if len(series) < 3:
        return {
            "mean": None,
            "Cv": None,
            "Cs": None,
            "Cs/Cv": None,
            "epsilon": None,
            "relative_rms_error_limit": MAX_MIN_RELATIVE_RMS_ERROR_LIMIT,
            "n": len(series),
            "period_days": period_days,
            "reliability_class": "Недостаточно данных",
            "warnings": ["Длина ряда < 3 лет. Статистические расчёты невозможны."]
        }

    basic = compute_basic_stats(
        series,
        use_normative_Cs=use_normative_Cs,
        relative_rms_error_limit=MAX_MIN_RELATIVE_RMS_ERROR_LIMIT,
    )
    basic["period_days"] = period_days
    return basic


def min_runoff_frequency_curve(
    min_series: pd.Series,
    P_values: list[float] | None = None,
    use_normative_Cs: bool = True
) -> pd.DataFrame:
    """
    Кривая обеспечённости минимальных стоков.

    Строит кривую обеспеченности минимального стока по наблюдённому ряду
    методом Крицкого-Менкеля через общий инструментарий core.stats.

    НОРМАТИВНЫЙ СТАТУС: ЧАСТИЧНОЕ ПРЕДМЕТНОЕ СООТВЕТСТВИЕ.
    СП 529.1325800.2023, п. 5.5.1 предписывает выполнять расчёт минимального
    стока по кривым обеспеченности со ссылкой на п. 5.1.3; применяемый здесь
    способ построения кривой этому предписанию предметно отвечает. Однако
    конкретная реализация через текущий КМ-инструментарий не должна
    объявляться VERIFIED по СП 529 только на основании этого соответствия:
    требования п. 5.5.2 (эмпирические кривые при изгибе 90 % – 97 %),
    п. 5.5.3 (нулевые расходы) и детали п. 5.1.3 здесь не реализованы, поэтому
    полная нормативная реализация п. 5.5 и п. 5.1.3 не заявляется.

    Parameters:
        min_series:.Series с годовыми минимальными расходами
        P_values: список обеспеченностей в процентах (по умолчанию нормативные)
        use_normative_Cs: использовать нормативное Cs = 2×Cv

    Returns:
        DataFrame с колонками: P_%, Q_min
    """
    if P_values is None:
        P_values = [80, 90, 95, 97, 99, 99.5, 99.9]

    series = min_series.dropna()

    if len(series) < 3:
        raise ValueError("Для построения кривой обеспечённости нужно ≥ 3 года данных")

    stats = compute_min_runoff_stats(series, use_normative_Cs=use_normative_Cs)
    mean_val = stats["mean"]
    Cv = stats["Cv"]
    Cs_over_Cv = stats.get("Cs/Cv", 2.0)

    km_curve = kritsky_menkel_quantiles(
        mean=mean_val,
        Cv=Cv,
        Cs_over_Cv=Cs_over_Cv,
        P_list=P_values
    )

    return pd.DataFrame({
        "P_%": km_curve["P_%"],
        "Q_min": km_curve["Q_p"].round(2)
    })


def ecosystem_minimum(
    mean_annual_flow: float,
    method: str = "tenpct"
) -> dict:
    """
    Экосистемный (экологический) минимальный сток.

    НОРМАТИВНЫЙ СТАТУС. Инженерный/исторический метод; соответствие
    СП 529.1325800.2023 не установлено; нормативный источник для экосистемного
    минимума в текущем корпусе отсутствует. Понятия «экологический
    (экосистемный) минимум», «санитарный расход» и «попуск» в СП 529
    не встречаются ни разу, поэтому приведённые ниже методы НЕ следуют из
    СП 529 и не являются его требованиями. Историческая реализация ранее
    атрибутировалась СП 33-101-2003, п. 5.41–5.43; эта атрибуция снята как
    действующая нормативная база, номера пунктов СП 33 на СП 529 не переносятся.

    Методы расчёта:
    - "tenpct": Q_экос = 0.1 × Qср (10% от среднегодового расхода)
    - "7q10": статистический 7-day 10-year minimum (требует суточного ряда)
    - "tessmann": метод Тессманна Q_экос = β × Qср × (1 + α × ln(1/P)),
      где β зависит от свойств водосбора (0.1–0.5)

    Parameters:
        mean_annual_flow: среднегодовой расход Qср (м³/с)
        method: метод расчёта ("tenpct", "7q10", "tessmann")

    Returns:
        Словарь с экосистемным расходом, методом и статусом соответствия
    """
    if mean_annual_flow <= 0:
        raise ValueError("Среднегодовой расход должен быть положительным")

    method_name = method.lower()

    if method_name == "tenpct":
        q_ecos = 0.1 * mean_annual_flow

    elif method_name == "tessmann":
        beta = 0.2
        alpha = 0.5
        P = 0.9
        q_ecos = beta * mean_annual_flow * (1 + alpha * np.log(1.0 / P))

    elif method_name == "7q10":
        q_ecos = 0.4 * mean_annual_flow
        return {
            "Q_ecosystem": round(q_ecos, 2),
            "method_used": "7Q10 (приблизительный)",
            "note": "Для точного расчёта 7Q10 используйте функцию q7_10() с суточным рядом расходов.",
            "compliance_status": "Требуется уточнение",
            "normative": (
                "Инженерный/исторический метод; соответствие "
                "СП 529.1325800.2023 не установлено; нормативный источник для "
                "экосистемного минимума в текущем корпусе отсутствует. "
                "Историческая атрибуция СП 33-101-2003, п. 5.41-5.43 снята "
                "как действующая нормативная база."
            )
        }

    else:
        raise ValueError(f"Неизвестный метод: '{method}'. Допустимые: 'tenpct', '7q10', 'tessmann'")

    if q_ecos < 0.1 * mean_annual_flow:
        compliance = "Ниже норматива (10% от Qср)"
    elif q_ecos <= 0.3 * mean_annual_flow:
        compliance = "Соответствует нормативу"
    else:
        compliance = "Выше норматива"

    return {
        "Q_ecosystem": round(q_ecos, 2),
        "method_used": method_name,
        "mean_annual_flow": mean_annual_flow,
        "compliance_status": compliance,
        "normative": (
            "Инженерный/исторический метод; соответствие "
            "СП 529.1325800.2023 не установлено; нормативный источник для "
            "экосистемного минимума в текущем корпусе отсутствует. "
            "Историческая атрибуция СП 33-101-2003, п. 5.41-5.43 снята "
            "как действующая нормативная база."
        )
    }


def q7_10(
    daily_series: pd.Series,
    years: pd.Series | None = None
) -> dict:
    """
    7-day 10-year minimum flow (7Q10) — показатель экосистемного минимума.

    НОРМАТИВНЫЙ СТАТУС. Инженерный/исторический метод; 7Q10 в
    СП 529.1325800.2023 не установлен; соответствие СП 529 не установлено.
    Пункт 5.5.1 СП 529 перечисляет минимальные средние расходы воды за 5 и
    10 сут (в районах с частыми паводками), а также среднесуточные,
    среднемесячные и 30-суточные некалендарные расходы; показатель 7Q10 в
    документе не обнаружен. Приведённый ниже алгоритм является инженерной
    конструкцией и НЕ является требованием СП 529. Историческая реализация
    ранее атрибутировалась СП 33-101-2003, п. 5.41–5.43 (и ошибочно — СП
    32.13330.2018, прил. Г); обе атрибуции сняты как действующая нормативная
    база, номера пунктов СП 33 на СП 529 не переносятся.

    Алгоритм (инженерный, не нормативный):
    1. Для каждого года находится минимальный 7-суточный средний расход.
    2. К полученному ряду годовых минимумов строится кривая обеспеченности.
    3. Извлекается значение при P = 90% (период возврата 10 лет).

    Parameters:
        daily_series: суточные расходы (м³/с)
        years: необязательный ряд годов

    Returns:
        Словарь с Q7_10, рядом годовых минимумов и статистикой
    """
    series = daily_series.dropna()

    if len(series) == 0:
        raise ValueError("Пустой ряд суточных расходов")

    if years is None:
        if hasattr(series.index, 'year'):
            years = pd.Series(series.index.year, index=series.index)
        elif 'year' in series.index.name if hasattr(series.index, 'name') else False:
            years = series.index
        else:
            raise ValueError("Не удалось определить годы. Укажите параметр years.")

    df = pd.DataFrame({'year': years.values, 'value': series.values})
    df = df.dropna(subset=['value'])

    annual_minima = {}
    for year in df['year'].unique():
        year_vals = df[df['year'] == year]['value'].values
        if len(year_vals) >= 7:
            min_avg = _sliding_window_min_mean(year_vals, 7)
            if min_avg is not None:
                annual_minima[year] = min_avg

    min_series = pd.Series(annual_minima, dtype=float)

    if len(min_series) < 3:
        raise ValueError(
            f"Недостаточно данных для расчёта 7Q10 ({len(min_series)} годов < 3). "
            "Требуется минимум 3 года с полными суточными данными."
        )

    stats = compute_min_runoff_stats(min_series, period_days=7)
    mean_val = stats["mean"]
    Cv = stats["Cv"]
    Cs_over_Cv = stats.get("Cs/Cv", 2.0)

    km_curve = kritsky_menkel_quantiles(
        mean=mean_val,
        Cv=Cv,
        Cs_over_Cv=Cs_over_Cv,
        P_list=[90]
    )

    q7_10_val = float(km_curve.iloc[0]["Q_p"])

    return {
        "Q7_10_value": round(q7_10_val, 2),
        "annual_minima": min_series.round(2),
        "stats": stats,
        "method": "7Q10",
        "normative": (
            "Инженерный/исторический метод; 7Q10 в СП 529.1325800.2023 не "
            "установлен; соответствие СП 529 не установлено. Пункт 5.5.1 СП 529 "
            "перечисляет 5- и 10-суточные минимумы, 7Q10 в документе не "
            "обнаружен. Историческая атрибуция СП 33-101-2003, п. 5.41-5.43 "
            "и ошибочная ссылка на СП 32.13330.2018, прил. Г сняты как "
            "действующая нормативная база."
        )
    }


