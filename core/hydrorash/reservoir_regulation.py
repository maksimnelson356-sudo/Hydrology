#   сверх потребления — холостые сбросы;
# - Приказ МПР РФ от 30.11.2007 № 314 «Об утверждении Методики расчёта
#   водохозяйственных балансов водных объектов» — использован ТОЛЬКО как
#   основание условия установившегося заполнения: при многолетнем
#   регулировании наполнение на начало ряда определяется итерациями до
#   совпадения объёмов наполнения на начало и конец ряда.
#
# ЗАЧЕМ НУЖЕН ИМЕННО ПЕРИОДИЧЕСКИЙ РЯД. Многолетнее регулирование — это
# НЕПРЕРЫВНЫЙ режим: расчётный период повторяется, и водохранилище обязано
# обслуживать сток за пределами последнего года записи. Максимальная
# просадка внутри одного периода этого не покрывает: вершина в конце периода и
# яма в начале следующего — разные точки кривой. Раньше просадка считалась
# только внутри периода, и на сбалансированном ряде (Σ(Q−D) = 0) ёмкость
# занижалась.
#
# ПРОВЕРКА ЗАМКНУТОСТИ. При Σ(Q−D) < 0 запас не восстанавливается: за
# каждый цикл водохранилище теряет |Σ|, и никакая конечная ёмкость не
# обеспечит работу без дефицита. Признак обнаруживается сравнением просадки
# на 2- и 3-периодном продолжении: при Σ ≥ 0 они совпадают, при Σ < 0 —
# расходятся. В таком случае конечное значение ёмкости НЕ ВЫДАЁТСЯ.


def _periodic_max_drawdown(c: np.ndarray, net: float, n_periods: int) -> float:
    """Максимальная просадка на n-периодном продолжении массовой кривой.

    Формула метода: V = max_{i<j} (C_i - C_j), где C — кумулятивная сумма
    (Q − D), C_0 = 0. Знак (Q − D) НЕ меняется: смена знака дала бы ту же
    величину, но смешивалась бы с величиной другой размерности.

    Цикл с «текущим максимумом» эквивалентен прямому перебору пар i < j
    (проверено на целочисленной сетке: 0 расхождений), но не квадратичен.
    """
    extended = np.concatenate([c + p * net for p in range(n_periods)])
    running_max = extended[0]
    max_drawdown = 0.0
    for value in extended[1:]:
        gap = running_max - value
        if gap > max_drawdown:
            max_drawdown = gap
        if value > running_max:
            running_max = value
    return float(max_drawdown)


def _simulate_cycle(
    q_d: np.ndarray, capacity: float, storage: float
) -> tuple[float, float, float]:
    """Один цикл баланса: S = min(V, max(0, S + (Q − D))).

    Returns:
        (storage_end, spill, unmet) — конечный запас, суммарный сброс
        (холостой) и суммарный непокрытый сток, все в м³/с.
    """
    spill = 0.0
    unmet = 0.0
    for delta in q_d:
        raw = storage + delta
        if raw < 0.0:
            unmet += -raw
            storage = 0.0
        elif raw > capacity:
            spill += raw - capacity
            storage = capacity
        else:
            storage = raw
    return storage, spill, unmet


def _steady_initial_storage(q_d: np.ndarray, capacity: float) -> float:
    """Установившееся начальное заполнение: итерация до S_нач = S_кон.

    Условие взято из приказа МПР РФ № 314: при многолетнем регулировании
    наполнение на начало первого года расчётного ряда определяется итерациями
    до совпадения объёмов наполнения на начало и конец ряда.

    Функция g(S0) = S_кон(S0) − S0 невозрастающая: шаг баланса
    min(V, max(0, ·)) не уменьшает и увеличивает не более чем на величину
    приращения, поэтому корень ищется бисекцией на [0, V].
    """
    if capacity <= 0.0:
        return 0.0
    low, high = 0.0, capacity
    for _ in range(200):
        mid = 0.5 * (low + high)
        end, _, _ = _simulate_cycle(q_d, capacity, mid)
        if end - mid > 0.0:
            low = mid
        else:
            high = mid
        if high - low < 1e-12:
            break
    return 0.5 * (low + high)


def _calculate_regulation_year_metrics(
    Q_annual: np.ndarray,
    demand_m3_s: float,
    capacity_m3: float,
    initial_storage_m3: float,
    year_seconds: float = SECONDS_PER_YEAR,
) -> dict:
    """Годовой водохозяйственный баланс с РАЗДЕЛЕНИЕМ двух разных понятий.

    Раньше год считался дефицитным по одному признаку — «итоговый запас
    S == 0». Это смешивало две разные величины и давало три измеренных
    расхождения:

    1. При V = 0 запас пуст каждый год, поэтому год помечался дефицитным даже
       при Q >= D, когда недобора не было вовсе (спрос обслуживался, излишек
       списывался);
    2. При Q == D годовой баланс тождественно нулю, то есть unmet = 0 всегда,
       но если запас пришёл пустым, он оставался пустым и год снова
       помечался — недобор последующих лет наследовался от провалившегося;
    3. Касание S = 0 ровно на границе года (S_raw == 0) давало unmet = 0 и
       всё равно флаг, хотя спрос был обслужен полностью.

    Теперь считаются ДВА независимых счётчика:

    unmet_i = max(0.0, -S_raw)
        ФАКТИЧЕСКИЙ НЕДОБОР спроса в году. Ненулевой тогда и только тогда,
        когда год не обеспечен. Это то, что «гарантированный расход»
        обещает не допустить.

    empty_i = (S == 0.0)
        ОПОРОЖНЕНИЕ водохранилища на конец года. Само по себе это не
        аномалия: водохранилище, полностью опустошённое и затем восполненное
        водами своего же года, обслужило спрос. При V = 0 этот признак
        постоянен и гарантии не касается.

    Для Q_i < D признаки совпадают, поэтому прежние значения
    guarantee_percent сохраняются. Расходятся они только там, где год
    обслужен, а запас пуст — и именно там прежний критерий врал.

    Returns:
        storage_end_m3 — запас на конец последнего года;
        storage_series_m3 — запас на конец каждого года, для публикации;
        deficit_years — число лет с unmet_i > 0;
        empty_years — число лет с S == 0 на конец;
        unmet_volume_m3 — суммарный недобор за период;
        max_unmet_volume_m3 — наибольший недобор за один год;
        guarantee_percent — (n - deficit_years) / n * 100.

    НОРМАТИВНЫЙ СТАТУС РАЗДЕЛЕНИЯ: UNKNOWN / SOURCE_MISSING. Определения
    «гарантированной отдачи», связывающего недобор с состоянием запаса, в
    локальном нормативном корпусе нет: термины «массовая кривая»,
    «накопленных расходов», «Риппл» не встречаются ни в одном из девяти PDF,
    а «гарантированная отдача» в СП 33 (стр. 9) и СП 529 (стр. 21)
    встречается по одному разу и только как ПРОЕКТНОЕ входное значение.
    Приписывать разделение СП 33 или СП 529 оснований нет.
    """
    storage = float(initial_storage_m3)
    cap = float(capacity_m3)

    deficit_years = 0
    empty_years = 0
    unmet_volume = 0.0
    max_unmet = 0.0
    series: list[float] = []

    for q_i in Q_annual:
        storage_raw = storage + (float(q_i) - demand_m3_s) * year_seconds
        unmet = -storage_raw if storage_raw < 0.0 else 0.0
        storage = cap if storage_raw > cap else (0.0 if storage_raw < 0.0 else storage_raw)

        if unmet > 0.0:
            deficit_years += 1
        if storage == 0.0:
            empty_years += 1

        unmet_volume += unmet
        if unmet > max_unmet:
            max_unmet = unmet
        series.append(storage)

    n_years = len(Q_annual)
    return {
        'storage_end_m3': storage,
        'storage_series_m3': series,
        'deficit_years': deficit_years,
        'empty_years': empty_years,
        'unmet_volume_m3': unmet_volume,
        'max_unmet_volume_m3': max_unmet,
        'guarantee_percent': (n_years - deficit_years) / n_years * 100.0,
    }


def _shortage_diagnostics(metrics: dict) -> dict:
    """Публикуемые поля недобора и опустошения.

    Объёмы отдаются в км³, потому что наружу отдаются объёмы, а годы и
    проценты остаются целыми. Ключи названы по образцу существующих полей
    (``required_volume_km3``), ничего не переименовывая.
    """
    return {
        'empty_years': metrics['empty_years'],
        'unmet_volume_km3': round(metrics['unmet_volume_m3'] / 1e9, 6),
        'max_unmet_volume_km3': round(metrics['max_unmet_volume_m3'] / 1e9, 6),
    }


def _ripple_diagnostics(ripple: dict) -> dict:
    """Публикуемые поля метода накопленных расходов.

    Имена подчинены существующему API (префикс ``required_volume_km3``) и
    дополняют его, ничего не переименовывая. Обозначения V₁/V₂ НЕ
    используются: в литературе они означают разные величины — в «Гидротехнических
    сооружениях» (том II) это расстояния между касательными при РАЗНЫХ
    процентах регулирования, то есть два варианта ёмкости, а не две
    компоненты одного проекта.

    Исходные м³/с пересчитываются в км³, потому что наружу отдаются объёмы.
    При невозможном режиме (Σ < 0) ёмкость равна NaN и НЕ подменяется нулём:
    нулевой объём означал бы, что регулирование не нужно, а не что оно
    невозможно.

    ПОЛЕ ``deficit_fraction`` ЗДЕСЬ НЕ УЧАСТВУЕТ. Оно по-прежнему считается по
    внутрипериодной просадке (``within_period_m3_s``), а не по требуемой
    ёмкости: иначе правка метода накопленных расходов задела бы это поле.
    Методология ``deficit_fraction`` — величина безразмерная, и смысл её здесь
    не проверяется; разбор отнесён к отдельной задаче, в этой правке она
    намеренно не затрагивается.
    """
    required_m3 = ripple['required_m3_s']
    initial_m3 = ripple['initial_storage_m3_s']
    spill_m3 = ripple['spill_m3_s']

    def to_km3(value: float) -> float:
        return round(value * SECONDS_PER_YEAR / 1e9, 6)

    return {
        'net_balance_m3_s': round(ripple['net_balance_m3_s'], 6),
        'initial_storage_km3': to_km3(initial_m3),
        'spill_volume_km3': to_km3(spill_m3),
        'stable_cycle': ripple['stable_cycle'],
        'regulation_possible': ripple['regulation_possible'],
        'capacity_unbounded': ripple['capacity_unbounded'],
        'closure_error_m3_s': round(ripple['closure_error_m3_s'], 9),
    }


def _ripple_mass_curve(q_d: np.ndarray) -> dict:
    """Метод накопленных расходов по Q − D: ёмкость, заполнение, сброс.

    Аргумент q_d — уже разность (Q_i − D) в м³/с, без NaN.

    ФИЗИЧЕСКИЙ КРИТЕРИЙ ЗАМКНУТОСТИ. Возможность установившегося цикла
    определяется суммой баланса за период, net = Σ(Q−D), а не сравнением
    просадок на продолжениях разной длины:

    - net > 0 — за каждый цикл водохранилище получает избыток; он уходит на
      холостой сброс, и цикл замыкается;
    - net = 0 — запас не растёт и не тает, цикл замыкается;
    - net < 0 — за каждый полный период запас уменьшается на |net| и никогда
      не восстанавливается. Конечной стационарной ёмкости не существует.

    Сравнение 2- и 3-периодной просадки даёт ТОТ ЖЕ ответ (для Σ ≥ 0 кривая
    повторяется либо поднимается, и просадка на двух периодах уже максимальна),
    но это следствие, а не признак. Оно оставлено как диагностика
    ``three_period_m3_s`` и в решении о возможности регулирования не участвует.

    Returns:
        required_m3_s — требуемая полезная регулирующая ёмкость в м³/с
        (для перевода в объём умножается на SECONDS_PER_YEAR);
        net_balance_m3_s — Σ(Q−D) за период;
        within_period_m3_s — просадка внутри одного периода (прежняя
        семантика поля deficit_fraction, см. сборщик диагностики);
        initial_storage_m3_s — установившееся начальное заполнение;
        spill_m3_s — холостой сброс за один установившийся цикл;
        stable_cycle — признак устойчивого (замкнутого) цикла;
        regulation_possible — False, если замкнутый режим невозможен;
        capacity_unbounded — True в этом случае;
        closure_error_m3_s — невязка S_кон − S_нач (диагностика);
        three_period_m3_s — просадка на 3-периодном продолжении (диагностика).
    """
    cumulative = np.concatenate([[0.0], np.cumsum(q_d)])
    net = float(cumulative[-1])

    # Допуск на сумму (Q−D): она накапливается за n лет, поэтому сравнение
    # ведётся по относительной величине. 1e-9 м³/с накопительно за 100 лет —
    # это 3 м³ за весь период, то есть несравнимо с любой реальной
    # погрешностью округления исходных расходов.
    net_tolerance = 1e-9 * max(1.0, abs(net))

    required_within = _periodic_max_drawdown(cumulative, net, 1)
    required_two = _periodic_max_drawdown(cumulative, net, 2)

    if net < -net_tolerance:
        return {
            "required_m3_s": float("nan"),
            "net_balance_m3_s": net,
            "within_period_m3_s": required_within,
            "initial_storage_m3_s": float("nan"),
            "spill_m3_s": float("nan"),
            "stable_cycle": False,
            "regulation_possible": False,
            "capacity_unbounded": True,
            "closure_error_m3_s": float("nan"),
            "three_period_m3_s": float("nan"),
        }

    initial = _steady_initial_storage(q_d, required_two)
    end, spill, _ = _simulate_cycle(q_d, required_two, initial)
    return {
        "required_m3_s": required_two,
        "net_balance_m3_s": net,
        "within_period_m3_s": required_within,
        "initial_storage_m3_s": initial,
        "spill_m3_s": spill,
        "stable_cycle": True,
        "regulation_possible": True,
        "capacity_unbounded": False,
        "closure_error_m3_s": end - initial,
        # Диагностика, не признак: при net ≥ 0 обязано совпадать с
        # required_m3_s, и расхождение означало бы ошибку в самой формуле.
        "three_period_m3_s": _periodic_max_drawdown(cumulative, net, 3),
    }



def multi_year_regulation(
    Q_annual: np.ndarray,
    demand_m3_s: float,
    V_max_km3: float | None = None,
    S_0_km3: float | None = None,
    target_guarantee: float = 95.0,
    mode: str = "natural_supply",
) -> dict:
    """
    Инженерный расчёт баланса и ёмкости водохранилища.

    НОРМАТИВНЫЙ СТАТУС: UNKNOWN. Функция не является реализацией
    СП 529.1325800.2023 (его статус для этого модуля — OUT_OF_SCOPE) и не
    претендует на подтверждённое соответствие СП 33-101-2003 или
    СП 58.13330.2019. Сверка СП 33-101-2003 по локальному первоисточнику
    (DOCS/NORMATIVE/HISTORICAL/, стр. 20) показала, что п. 7.2 и 7.3
    посвящены отсутствию гидрометрических наблюдений и выбору рек-аналогов,
    а не регулированию стока, — прежняя привязка к ним является CONFLICT.
    Положения о регулировании стока не верифицированы в рамках текущего
    аудита.

    МЕТОД НАКОПЛЕННЫХ РАСХОДОВ («МЕТОД РИППЛА»). Далее в коде и в тексте
    сохраняется название метода как название используемого алгоритма
    (массовая кривая / метод накопленных расходов). Нормативная
    принадлежность не верифицирована в рамках текущего аудита: в СП 529
    метода Риппла нет, а в проверенных п. 7.2 и 7.3 СП 33-101-2003 он
    не упомянут.
    Статус: REFERENCE. Последовательный водохозяйственный
    баланс, реализованный ниже, имеет вид
        S_{i+1} = min(V_max, max(0, S_i + (Q_i - D) * T))
    и является инженерной конструкцией текущей реализации.

    КРИТЕРИЙ «ГАРАНТИИ». Фактически вычисляется доля лет, в которых
    водохранилище не зарегистрировало годовой дефицит (S == 0 на конец
    расчётного года):
        guarantee = (N - N_def) / N * 100 %
    Это критерий текущей инженерной реализации. Формула (N − N_def)/N · 100 %
    в проверенных п. 7.2 и 7.3 СП 33-101-2003 не обнаружена: эти пункты
    посвящены отсутствию гидрометрических наблюдений и выбору рек-аналогов,
    поэтому прежняя ссылка на них является CONFLICT. Соответствие
    не верифицировано в рамках текущего аудита. Статус:
    LEGACY. Величина не является обеспеченностью отдачи в
    смысле СП 529: кривая обеспеченности здесь не строится. Отдельно
    отмечается лишь то, что СП 529 п. 5.2.4 (стр. 21) упоминает обеспеченность
    гарантированной отдачи как входное ПРОЕКТНОЕ значение; методику его
    расчёта СП 529 не даёт, и настоящая функция её не реализует.

    Режимы работы (все три — инженерные расчёты баланса/ёмкости):
    - guarantee_for_volume: последовательный баланс с ограничением объёма
      S по V_max; по умолчанию S_0 = V_max;
    - volume_for_guarantee: бинарный поиск минимального V_max, при котором
      рассчитанная величина guarantee достигает target_guarantee;
    - natural_supply: ТОЛЬКО статистика исходного ряда, без баланса. Этот
      режим фактически НЕ использует V_max_km3 и S_0_km3 — они не влияют на
      результат. Гарантия здесь = P(Q >= D).

    Потери (испарение, фильтрация, ледовые) — NOT_IMPLEMENTED: в расчёте не
    участвуют, T = календарные 365 сут без какого-либо коэффициента потерь.

    Parameters:
        Q_annual: среднегодовые расходы за ряд лет, м3/с
        demand_m3_s: среднегодовой забор (потребление), м3/с
        V_max_km3: полезный объём водохранилища, км³ (обязателен для режимов регулирования)
        S_0_km3: начальный запас в водохранилище, км³ (по умолчанию = V_max)
        target_guarantee: целевое значение доли лет без дефицита, %
            (инженерное допущение; нормативное происхождение не установлено)
        mode: режим работы
            - "guarantee_for_volume": даны V_max, D — вычислить гарантию
            - "volume_for_guarantee": даны D, target_guarantee — найти V_max
            - "natural_supply": только статистика P(Q >= D) (обратная совместимость)

    Returns:
        Dict с результатами расчёта
    """
    Q = np.array(Q_annual, dtype=float)
    Q = Q[~np.isnan(Q)]
    n = len(Q)

    if n == 0:
        raise ValueError("Ряд притоков не может быть пустым")

    Q_mean = float(np.mean(Q))
    Q_min = float(np.min(Q))

    # Проверка забора
    if demand_m3_s <= 0:
        raise ValueError("Забор должен быть положительным")

    # Режим обратной совместимости: только статистика исходного ряда
    if mode == "natural_supply":
        guarantee = float((Q >= demand_m3_s).mean() * 100) if n > 0 else 0
        natural_supply = guarantee

        # Метод накопленных расходов по Q − D на ПЕРИОДИЧЕСКОМ продолжении.
        # Название «метод Риппла» — обозначение алгоритма, не нормативная
        # ссылка: ни в СП 529, ни в проверенных п. 7.2 и 7.3 СП 33-101-2003
        # он не упомянут, а в локальном корпусе термин не найден ни разу.
        # Расчёт — в _ripple_mass_curve, общем для всех трёх режимов.
        ripple = _ripple_mass_curve(Q - demand_m3_s)
        V_ripple_m3 = ripple['required_m3_s'] * SECONDS_PER_YEAR
        V_ripple_km3 = V_ripple_m3 / 1e9

        return {
            'required_volume_km3': round(V_ripple_km3, 3),
            'required_volume_mln_m3': round(V_ripple_m3 / 1e6, 1),
            'guarantee_percent': round(guarantee, 1),
            'natural_supply_percent': round(natural_supply, 1),
            'Q_mean': round(Q_mean, 2),
            'Q_demand': round(demand_m3_s, 2),
            'deficit_fraction': round(float(ripple['within_period_m3_s']) / Q_mean, 3) if Q_mean > 0 else 0,
            'balance_cumulative': np.cumsum(Q - demand_m3_s).tolist(),
            **_ripple_diagnostics(ripple),
            'warning': 'Режим natural_supply: гарантия = P(Q >= D), не учитывает регулирование!' if demand_m3_s <= Q_mean else 'Забор > среднего стока! Нужно много летнее регулирование.',
        }

# Для режима volume_for_guarantee V_max не требуется на входе (будет найден)
    if mode == "volume_for_guarantee":
        V_max = None
    else:
        # Для режима guarantee_for_volume V_max обязателен
        if V_max_km3 is None:
            raise ValueError("Для режима 'guarantee_for_volume' параметр V_max_km3 обязателен")
        V_max = V_max_km3 * 1e9  # м³
        if V_max <= 0:
            raise ValueError("V_max должен быть положительным")

    # Валидация S_0 (только для режимов с V_max)
    if mode != "volume_for_guarantee":
        S_0 = V_max if S_0_km3 is None else S_0_km3 * 1e9
        if not (0 <= S_0 <= V_max):
            raise ValueError("S_0 должен быть в диапазоне [0, V_max]")
    else:
        S_0 = None

    if not (0 < target_guarantee <= 100):
        raise ValueError("target_guarantee должен быть в (0, 100]")

    D = demand_m3_s
    T = SECONDS_PER_YEAR

    if mode == "guarantee_for_volume":
        # Даны V_max, D — вычислить гарантию.
        # Баланс и оба счётчика считает _calculate_regulation_year_metrics:
        # deficit_years по фактическому недобору, empty_years по опустошению.
        metrics = _calculate_regulation_year_metrics(Q, D, V_max, S_0, T)
        guarantee = metrics['guarantee_percent']
        balance_series = [S_0 / 1e9] + [s / 1e9 for s in metrics['storage_series_m3']]

        # Метод накопленных расходов по Q − D на периодическом продолжении —
        # тот же расчёт, что и в natural_supply (общая функция).
        ripple = _ripple_mass_curve(Q - D)
        V_ripple_m3 = ripple['required_m3_s'] * T

        return {
            'required_volume_km3': round(V_ripple_m3 / 1e9, 3),
            'required_volume_mln_m3': round(V_ripple_m3 / 1e6, 1),
            'guarantee_percent': round(guarantee, 1),
            'deficit_years': metrics['deficit_years'],
            'Q_mean': round(Q_mean, 2),
            'Q_demand': round(D, 2),
            'deficit_fraction': round(float(ripple['within_period_m3_s']) / Q_mean, 3) if Q_mean > 0 else 0,
            'balance_cumulative': np.cumsum(Q - D).tolist(),
            'balance_series_km3': balance_series,
            'V_max_km3': round(V_max / 1e9, 3),
            'S_0_km3': round(S_0 / 1e9, 3),
            'target_guarantee': target_guarantee,
            **_shortage_diagnostics(metrics),
            **_ripple_diagnostics(ripple),
        }

    elif mode == "volume_for_guarantee":
        # Даны D, target_guarantee — найти V_max (бинарный поиск)
        if D >= Q_mean:
            raise ValueError("Для mode=volume_for_guarantee забор должен быть < среднего притока")

        # Нижняя граница: 0
        # Верхняя граница: оценка по методу накопленных расходов + запас.
        # Расчёт тот же, что и в двух других режимах (общая функция).
        # «Метод Риппла» — обозначение алгоритма, не нормативная ссылка.
        ripple = _ripple_mass_curve(Q - D)
        max_drawdown = ripple['required_m3_s']
        # При D < Q_mean, что проверено выше, Σ(Q−D) = n·(Q_mean − D) > 0, то
        # есть замкнутый режим заведомо возможен и ёмкость конечна. Проверка
        # оставлена явно: молчаливый NaN в верхней границе бинарного поиска
        # сломал бы его сравнениями, а это труднее заметить, чем отказ.
        if not ripple['regulation_possible']:
            raise ValueError(
                "Для mode=volume_for_guarantee требуется конечная ёмкость, "
                "но замкнутый многолетний режим невозможен: "
                f"Σ(Q−D) = {ripple['net_balance_m3_s']:.4g} м³/с < 0, запас "
                "не восстанавливается. Снизьте забор или увеличьте ряд."
            )
        # ИНЖЕНЕРНАЯ ЭВРИСТИКА, не норматив: множитель запаса 2.
        # Нормативное происхождение не установлено (SOURCE_MISSING).
        # Приписывать его СП 529, СП 33 или СП 58 оснований нет.
        V_upper = max_drawdown * T * 2  # с запасом 2x

        if V_upper <= 0:
            # ИНЖЕНЕРНАЯ ЭВРИСТИКА, не норматив: запасной множитель 1.5.
            # Нормативное происхождение не установлено (SOURCE_MISSING).
            V_upper = (Q_mean - D) * T * 1.5  # fallback

        # Бинарный поиск минимального V_max, при котором гарантия >= целевой.
        # Инженерный численный приём, не метод какого-либо стандарта.
        #
        # ДОПУСК СХОДИМОСТИ. Раньше критерий был чисто абсолютным:
        # V_high - V_low < 1e6 м³. Для водохранилища объёмом менее 1 млн м³
        # (порог: max_drawdown < 0.0159 м³/с) допуск превышал сам объём,
        # условие выполнялось ДО первой итерации, тело цикла не выполнялось
        # ни разу, и наружу уходила верхняя граница V_high как «найденное
        # решение». Теперь критерий комбинированный — относительная часть и
        # абсолютный пол.
        #
        # ЗНАЧЕНИЯ НЕ ВВЕДЕНЫ ЗДЕСЬ, а взяты из практики этого же файла:
        # относительная 1e-9 уже применяется для допуска на сумму (Q−D) в
        # _ripple_mass_curve (см. net_tolerance в теле этой функции, с тем же
        # обоснованием — накопленная численная погрешность исходных расходов
        # несравнимо больше любой сходимости бисекции), а пол 1.0 там же
        # защищает от нулевого масштаба. Здесь единицы — м³, и пол 1 м³ равен
        # наименьшему осмысленному объёму; он же гарантирует завершение цикла,
        # когда истинный ответ равен нулю (ветка max_drawdown == 0).
        #
        # ЧИСЛЕННЫЙ КРИТЕРИЙ АЛГОРИТМА, не нормативный параметр: проектом
        # согласованной величины допуска для этого поиска не зафиксировано.
        volume_abs_tol = 1.0   # м³
        volume_rel_tol = 1e-9  # доля от масштаба поиска

        V_low = 0.0
        V_high = V_upper
        best_V = V_high

        # 50 итераций — с запасом. Для диапазона порядка 4.4e9 м³ абсолютный
        # пол 1 м³ потребовал бы ≈32 делений, относительный 1e-9 — ≈30.
        # Это два критерия одного max(), а не последовательные этапы: при
        # больших объёмах 1e-9·scale > 1 и связывает относительный, поэтому
        # фактически наблюдается ≈31 итерация. Лимит 50 не достигается.
        for _ in range(50):
            scale = max(abs(V_high), abs(V_low), 1.0)
            if V_high - V_low <= max(volume_abs_tol, volume_rel_tol * scale):
                break

            V_mid = (V_low + V_high) / 2

            # Проверка гарантии для V_mid. Тот же helper, что и в остальных
            # режимах: иначе критерий дефицита разошёлся бы между ними.
            probe = _calculate_regulation_year_metrics(Q, D, V_mid, V_mid, T)
            guarantee = probe['guarantee_percent']

            if guarantee >= target_guarantee:
                best_V = V_mid
                V_high = V_mid
            else:
                V_low = V_mid

        # Финальная проверка для best_V — по фактическому недобору.
        metrics = _calculate_regulation_year_metrics(Q, D, best_V, best_V, T)
        guarantee = metrics['guarantee_percent']

        # ЯВНАЯ ПРОВЕРКА ДОСТАТОЧНОСТИ ГРАНИЦЫ (обязательна, а не косметика).
        #
        # best_V инициализируется значением V_high, поэтому состояние «решение
        # не найдено» снаружи неотличимо от состояния «найдено ровно на
        # границе». Различить их можно ТОЛЬКО фактической проверкой достижения
        # целевой гарантии в найденной точке, что здесь и делается. Сравнение
        # чисел (best_V == V_high) для этой цели непригодно: решение,
        # найденное рядом с границей, неотличимо от случая, когда границы
        # попросту не хватило.
        if guarantee < target_guarantee:
            raise ValueError(
                "Для mode=volume_for_guarantee требуемая гарантия "
                f"{target_guarantee:g} % НЕ ПОДТВЕРЖДЕНА. Верхняя граница "
                f"поиска {V_upper:.6g} м³ оказалась недостаточной либо "
                "бинарный поиск не смог найти решение. Найденное значение "
                f"{best_V:.6g} м³ обеспечивает лишь {guarantee:.1f} % и НЕ "
                "является подтверждённым минимальным требуемым объёмом. "
                "Снизьте целевую гарантию, уменьшите забор или увеличьте ряд."
            )

        return {
            'required_volume_km3': round(best_V / 1e9, 3),
            'required_volume_mln_m3': round(best_V / 1e6, 1),
            'guarantee_percent': round(guarantee, 1),
            'deficit_years': metrics['deficit_years'],
            'Q_mean': round(Q_mean, 2),
            'Q_demand': round(D, 2),
            'target_guarantee': target_guarantee,
            'achieved_guarantee': round(guarantee, 1),
            **_shortage_diagnostics(metrics),
            **_ripple_diagnostics(ripple),
        }

    else:
        raise ValueError(f"Неизвестный mode: {mode}. Доступные: 'guarantee_for_volume', 'volume_for_guarantee', 'natural_supply'")


def storage_yield_curve(
    Q_annual: np.ndarray,
    V_range_km3: list[float] | None = None,
    target_guarantee: float = 95.0,
) -> pd.DataFrame:
    """
    Инженерный численный расчёт зависимости допустимого спроса от объёма.

    НОРМАТИВНЫЙ СТАТУС: UNKNOWN. Функция не является реализацией нормативной
    кривой «объём — гарантированная отдача». Прежняя ссылка на СП 33-101-2003
    п. 7.3 является CONFLICT: по локальному первоисточнику (стр. 20) этот
    пункт посвящён общим условиям выбора рек-аналогов, а не гарантированной
    отдаче. СП 529 для этого модуля имеет статус OUT_OF_SCOPE. Соответствие
    не верифицировано в рамках текущего аудита.

    ФАКТИЧЕСКИ ДЕЛАЕТ. Для каждого V_max из V_range_km3 выполняется бинарный
    поиск максимального допустимого забора D из интервала (0, Q_mean) так,
    чтобы доля лет без зарегистрированного годового дефицита была не меньше
    target_guarantee. Баланс моделируется годовым шагом с ограничением объёма,
    начальное заполнение S_0 = V_max.

    ГАРАНТИЯ И ОТДАЧА ПУБЛИКУЮТСЯ ДЛЯ ОДНОГО ЗНАЧЕНИЯ. Отдача округляется
    консервативно, вниз до двух знаков, ДО финальной проверки, и именно это
    округлённое значение проверяется и печатается. Раньше отдача печаталась
    как round(best_D, 2), а гарантия считалась на неокруглённом best_D, и
    при округлении вверх пара (Q_max_demand, achieved_guarantee) становилась
    противоречивой: например, для ряда [20, 80] × 10 при V = 0,05 км³
    истинный максимум отдачи 21,5854896 м³/с печатался как 21,59, при котором
    дефицитны 10 лет из 20 и не покрыто 1,42 · 10⁶ м³, — а колонка
    achieved_guarantee показывала при этом 100 %. Округление вниз не даёт
    опубликованному спросу превысить проверенный, поэтому кривая остаётся
    физически реализуемой.

    НОРМАТИВНЫЙ СТАТУС НЕ МЕНЯЕТСЯ: UNKNOWN, как и прежде. Численной формулы
    «объём — гарантированная отдача» в локальном нормативном корпусе нет
    (SOURCE_MISSING), и правка ниже — устранение внутреннего противоречия
    публикуемой пары величин, а не приведение функции к нормативному виду.
    Год считается дефицитным по ФАКТИЧЕСКОМУ НЕДОБОРУ unmet_i > 0, а не по
    опустошению запаса, поэтому при V_km3 = 0 отдача НЕ обязана быть нулевой.
    Для физически допустимого ряда Q >= 0 она определяется минимальным
    годовым притоком min(Q) с учётом критерия гарантии и округления вниз
    до 0.01; поведение зафиксировано тестом.

    Parameters:
        Q_annual: среднегодовые расходы
        V_range_km3: список объёмов для расчёта, км³
        target_guarantee: целевое значение доли лет без дефицита, %
            (инженерное допущение; нормативное происхождение не установлено)

    Returns:
        DataFrame: V_km3, Q_max_demand (максимальный допустимый забор),
        achieved_guarantee
    """
    if V_range_km3 is None:
        V_range_km3 = [0.1, 0.5, 1, 2, 3, 5, 8, 10, 15, 20]

    Q = np.array(Q_annual, dtype=float)
    Q = Q[~np.isnan(Q)]
    Q_mean = float(np.mean(Q))

    if np.any(Q < 0):
        raise ValueError(
            f"Расходы не могут быть отрицательными: минимум {Q.min():.6g} м³/с. "
            "Отрицательный сток физически недопустим; если это пропуск данных — "
            "передайте его как NaN, а не как число."
        )

    if Q_mean <= 0:
        raise ValueError("Средний приток должен быть положительным")

    if not (0 < target_guarantee <= 100):
        raise ValueError("target_guarantee должен быть в (0, 100]")

    rows = []
    for V_km3 in V_range_km3:
        # Фактический расчёт: для данного V_max найти максимальный D
        # такое, что гарантия (доля лет без дефицита) >= target_guarantee.
        # Единицы: V_max = км3 -> м3; баланс Q[м3/с] - D[м3/с] * 86400*365[с].
        V_max = V_km3 * 1e9

        # Бинарный поиск D — инженерный численный приём, не метод стандарта.
        D_low = 0.0
        D_high = Q_mean
        best_D = 0.0

        for _ in range(40):
            if D_high - D_low < 1e-3:  # точность 0.001 м³/с
                break

            D_mid = (D_low + D_high) / 2

            # Проверка гарантии для D_mid. Тот же helper, что и в
            # multi_year_regulation: определение дефицита обязано совпадать,
            # иначе кривая отдачи строилась бы по другой семантике, чем
            # остальные режимы модуля.
            probe = _calculate_regulation_year_metrics(
                Q, D_mid, V_max, V_max, SECONDS_PER_YEAR
            )
            guarantee = probe['guarantee_percent']

            if guarantee >= target_guarantee:
                best_D = D_mid
                D_low = D_mid
            else:
                D_high = D_mid

        # ОКРУГЛЕНИЕ ВНИЗ ДО ПРОВЕРКИ. Публикуемое значение отдачи обязано
        # совпадать с проверяемым, иначе колонка achieved_guarantee
        # сертифицирует одну величину, а отдача публикует другую. floor, а не
        # round: округление вверх увеличило бы спрос выше проверенного и
        # вернуло бы ровно то противоречие, которое здесь устраняется.
        best_D = math.floor(best_D * 100.0) / 100.0

        # Финальная проверка — на том же значении, которое будет опубликовано,
        # и по фактическому недобору, а не по опустошению запаса.
        metrics = _calculate_regulation_year_metrics(
            Q, best_D, V_max, V_max, SECONDS_PER_YEAR
        )
        guarantee = metrics['guarantee_percent']

        # ЗАЩИТНЫЙ ИНВАРИАНТ, а не замена проверки отрицательных расходов выше.
        # Для физически допустимого ряда (Q >= 0) путь недостижим: при D = 0
        # недобор тождественно равен нулю, поэтому цель (0, 100] достижима при
        # любом V. Инвариант оставлен намеренно: он защищает функцию, если
        # модель когда-нибудь перестанет давать 100 % при нулевом заборе
        # (например, при появлении потерь или негодового шага). Без него
        # недостижимая цель молча публиковалась бы строкой с отдачей 0.
        if guarantee < target_guarantee:
            raise ValueError(
                f"При V_max = {V_km3:g} км³ цель {target_guarantee:g} % недостижима "
                f"даже при нулевом заборе: гарантия {guarantee:.1f} %. Вероятная причина — "
                "отрицательные расходы в ряду: недобор возникает независимо от запаса."
            )

        rows.append({
            'V_km3': V_km3,
            'Q_max_demand': round(best_D, 2),
            'achieved_guarantee': round(guarantee, 1),
            'target_guarantee': target_guarantee,
            'deficit_years': metrics['deficit_years'],
            'empty_years': metrics['empty_years'],
            'unmet_volume_km3': round(metrics['unmet_volume_m3'] / 1e9, 6),
        })

    return pd.DataFrame(rows)


def reservoir_storage_calculation(
    H_list: list[float],
    A_list: list[float],
    method: str = 'trapezoid',
) -> dict:
    """
    Геометрический расчёт накопленного объёма по дискретным значениям
    отметки H и площади A, метод трапеций.

    НОРМАТИВНЫЙ СТАТУС: REFERENCE / PARTIAL. Это геометрический (инженерный)
    расчёт; нормативная принадлежность к СП 529.1325800.2023 отсутствует
    (для этого модуля СП 529 имеет статус OUT_OF_SCOPE).

    Фактическая формула в коде, с учётом перевода в км³:
        dV = (A_i + A_{i+1}) / 2 * (H_{i+1} - H_i) / 1000   [км³]
    Множитель 1/1000 переводит произведение «км² · м» в км³, поскольку
    1 км² · 1 м = 10⁻³ км³. Без него результат был бы в единицах «км²·м».
    Накопление ведётся от нижнего переданного уровня, поэтому V_total включает
    мёртвый объём; полезный и мёртвый объёмы функцией НЕ разделяются.

    Параметр `method` в текущей реализации не используется: всегда применяется
    трапеция. Это технический долг, здесь только фиксируется; параметр и
    расчёт не изменяются.

    ЭТО НЕ РАСЧЁТ ПРОПУСКА ПАВОДКА. Функция не моделирует трансформацию
    паводочного гидрографа, водосброс, свободный объём или уровни: см.
    NOT_IMPLEMENTED в шапке модуля.

    Parameters:
        H_list: уровни, м (по возрастанию)
        A_list: площади зеркала, км²

    Returns:
        Dict: cumulative_volumes, table_df
    """
    H = np.array(H_list)
    A = np.array(A_list)

    # Валидация: H должен быть строго возрастающим
    if len(H) < 2:
        raise ValueError("Нужно минимум 2 уровня")
    if len(H) != len(A):
        raise ValueError("Длины списков H и A должны совпадать")
    if not np.all(np.diff(H) > 0):
        raise ValueError("Уровни H должны быть строго возрастающими")

    V_cumulative = [0.0]
    for i in range(1, len(H)):
        dV = (A[i - 1] + A[i]) / 2 * (H[i] - H[i - 1]) / 1000.0
        V_cumulative.append(V_cumulative[-1] + dV)

    df = pd.DataFrame({
        'H_m': H,
        'A_km2': A,
        'V_cumulative_km3': [round(v, 4) for v in V_cumulative],
    })

    return {
        'table': df,
        'V_total_km3': round(float(V_cumulative[-1]), 4),
    }


def annual_regulation_table(
    Q_monthly: np.ndarray,
    demand_m3_s: float,
    V_useful_km3: float = 1.0,
) -> pd.DataFrame:
    """
    Инженерный месячный водохозяйственный баланс.

    НОРМАТИВНЫЙ СТАТУС: UNKNOWN / CONFLICT относительно претензии на
    полноценное регулирование. Функция НЕ является реализацией СП
    529.1325800.2023 п. 5.2.4: этот пункт (стр. 21) касается расчётного
    календарного внутригодового распределения стока и упоминает обеспеченность
    гарантированной отдачи только как входное ПРОЕКТНОЕ значение. Методику
    регулирования водохранилища п. 5.2.4 не даёт, и настоящая функция её не
    реализует. Искусственные соответствия п. 5.2.4 искать не следует.

    ФАКТИЧЕСКИ ДЕЛАЕТ. Помесячно накапливает разность притока и забора:
        dV = (Q_in - Q_out) * дней * 86400 / 1e9   [км³]
    Единицы: [м³/с] · [сут] · 86400 [с/сут] -> м³; / 1e9 -> км³.
    Длины месяцев заданы списком с суммой 365 сут.

    ЗАФИКСИРОВАННЫЕ ОГРАНИЧЕНИЯ, НЕ ИСПРАВЛЯЮТСЯ здесь. Функция не является
    полноценной методикой регулирования, поскольку:
      - объём водохранилища НЕ ограничивается величиной V_useful_km3: баланс
        накапливается без клампинга, и при V_in < V_out он уходит в отрицательные
        значения, а колонка «Заполнен_%» может выходить за 0…100;
      - начальный объём не задаётся: расчёт начинается с нуля в январе;
      - длины месяцев фиксированы (февраль всегда 28 сут, високосные годы не
        учитываются);
      - если ряд короче 12 значений, недостающие месяцы получают нулевой приток
        молча, без диагностики.

    Функция не связана с multi_year_regulation: это отдельная реализация
    баланса с другой логикой ограничения объёма.

    Parameters:
        Q_monthly: 12 средних месячных расходов, м3/с
        demand_m3_s: средний забор, м3/с
        V_useful_km3: полезный объём, км³. В текущей реализации используется
            ТОЛЬКО как делитель в колонке «Заполнен_%» и не ограничивает баланс.

    Returns:
        DataFrame с месячным балансом
    """
    months = ['Янв', 'Фев', 'Мар', 'Апр', 'Май', 'Июн',
              'Июл', 'Авг', 'Сен', 'Окт', 'Ноя', 'Дек']

    # Календарное инженерное допущение: сумма 365 сут, февраль всегда 28.
    # Не нормативное требование; високосные годы не учитываются.
    days = [31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31]

    rows = []
    V_balance = 0
    for i, (m, d) in enumerate(zip(months, days)):
        Q_in = Q_monthly[i] if i < len(Q_monthly) else 0
        Q_out = demand_m3_s
        dV = (Q_in - Q_out) * d * 86400 / 1e9
        V_balance += dV

        rows.append({
            'Месяц': m,
            'Q_приток': round(Q_in, 2),
            'Q_забор': round(Q_out, 2),
            'dV_km3': round(dV, 4),
            'V_баланс_km3': round(V_balance, 4),
            'Заполнен_%': round(V_balance / V_useful_km3 * 100, 1) if V_useful_km3 > 0 else 0,
        })

    return pd.DataFrame(rows)
