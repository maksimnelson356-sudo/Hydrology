# 2. Нет ложных нулей
# --------------------------------------------------------------------------- #

@pytest.mark.parametrize("cv", sorted(CLIPPED_TO_ZERO))
def test_no_false_clipping_to_zero(cv: float) -> None:
    """Ни одна из 33 ячеек, что раньше резалась в ноль, больше не нулевая."""
    cases = CLIPPED_TO_ZERO[cv]
    p_pct = np.array(sorted(cases), dtype=float)
    got = kritsky_menkel_ppf(p_pct / 100.0, 1.0, cv, cv)
    assert np.all(got > 0.0), (
        f"Cv={cv}: ложные нули вернулись в {list(np.array(p_pct)[got == 0])}. "
        "Хвост снова обрезается - в.table занесено не то."
    )
    for p, g in zip(p_pct, got, strict=True):
        assert g == pytest.approx(cases[p], rel=2e-3, abs=0.0), (
            f"Cv={cv}, P={p} %: {g:.6g} против первоисточника {cases[p]:.6g}"
        )


def test_whole_tail_block_is_positive() -> None:
    """Сплошная проверка блока, а не по одной ячейке."""
    cvs = [0.4, 0.5, 0.6, 0.7, 0.8, 0.9, 1.0]
    probs = np.array([90, 95, 97, 99, 99.5, 99.7, 99.9]) / 100.0
    for cv in cvs:
        q = kritsky_menkel_ppf(probs, 1.0, cv, cv)
        assert np.all(q > 0.0), f"Cv={cv}: есть нули - {q}"
        assert np.all(np.isfinite(q)), f"Cv={cv}: не-конечные значения - {q}"


def test_tail_is_monotone_in_p() -> None:
    """Первоисточник убывает по обеспеченности - таблица после правки тоже."""
    probs = np.array([90, 95, 97, 99, 99.5, 99.7, 99.9]) / 100.0
    for cv in [0.4, 0.5, 0.6, 0.7, 0.8, 0.9, 1.0]:
        q = kritsky_menkel_ppf(probs, 1.0, cv, cv)
        assert np.all(np.diff(q) < 0.0), f"Cv={cv}: хвост не убывает - {q}"


def test_body_of_curve_still_agrees_with_paper() -> None:
    """Правка хвоста не сдвинула тело кривой (P = 5...90 %)."""
    body = {0.4: {5.0: 1.70, 10.0: 1.54, 50.0: 0.972, 90.0: 0.500},
            0.8: {5.0: 2.53, 10.0: 2.16, 50.0: 0.836, 90.0: 0.092},
            1.0: {5.0: 3.02, 10.0: 2.55, 50.0: 0.665, 90.0: 0.019}}
    for cv, cells in body.items():
        for p, exp in cells.items():
            got = float(kritsky_menkel_ppf(np.array([p / 100.0]), 1.0, cv, cv)[0])
            assert got == pytest.approx(exp, rel=2e-3, abs=0.0), (
                f"Cv={cv}, P={p} %: {got:.4f} против {exp} - правка хвоста "
                "задela тело кривой"
            )


