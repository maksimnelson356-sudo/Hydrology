def test_output_shape_and_positivity_preserved() -> None:
    """Форма, конечность и неотрицательность - как у прежней реализации."""
    probs = np.array([0.001, 0.01, 0.05, 0.1, 0.5, 0.9, 0.99, 0.999])
    for cv in (0.1, 0.3, 0.5):
        for cs in (-0.2, -0.5, -1.0):
            q = kritsky_menkel_ppf(probs, mean=100.0, cv=cv, cs=cs)
            assert q.shape == probs.shape
            assert np.all(np.isfinite(q)), f"не-конечные при cv={cv}, cs={cs}: {q}"
            assert np.all(q >= 0.0), f"отрицательные при cv={cv}, cs={cs}: {q}"


def test_negative_cs_still_monotone() -> None:
    """При Cs < 0 квантили убывают по обеспеченности (CR-2)."""
    probs = np.array([0.001, 0.01, 0.05, 0.1, 0.3, 0.5, 0.7, 0.9, 0.99])
    q = kritsky_menkel_ppf(probs, mean=50.0, cv=0.4, cs=-0.6)
    assert np.all(np.diff(q) <= 1e-9 + 1e-6 * np.abs(q[:-1])), f"немонотонно: {q}"


def test_mean_scaling_is_linear() -> None:
    """Ордината - произведение табличного kp на среднее."""
    probs = np.array([0.01, 0.5, 0.9, 0.99])
    one = kritsky_menkel_ppf(probs, 1.0, 0.4, 0.4)
    fifty = kritsky_menkel_ppf(probs, 50.0, 0.4, 0.4)
    np.testing.assert_allclose(fifty, one * 50.0, rtol=1e-12)


def test_degenerate_inputs_keep_previous_behaviour() -> None:
    """mean <= 0 -> NaN, cv <= 0 -> mean (как было)."""
    probs = np.array([0.5])
    assert np.isnan(kritsky_menkel_ppf(probs, 0.0, 0.4, 0.4)[0])
    assert kritsky_menkel_ppf(probs, 100.0, 0.0, 0.4)[0] == 100.0


def test_probabilities_outside_zero_one_are_nan() -> None:
    """P <= 0 и P >= 1 вне области определения табличной кривой.

    Проверяются именно недопустимые значения; P = 0,5 внутри области и
    обязан остаться числом.
    """
    probs = np.array([0.0, 1.0, -0.1, 1.5])
    q = kritsky_menkel_ppf(probs, 100.0, 0.4, 0.4)
    assert np.all(np.isnan(q)), f"ожидался NaN, получено {q}"

    inside = float(kritsky_menkel_ppf(np.array([0.5]), 100.0, 0.4, 0.4)[0])
    assert np.isfinite(inside), "P = 0,5 обязан быть числом"


def test_get_ordinates_is_still_the_table_source() -> None:
    """production-функция читает именно таблицу, а не считает заново."""
    probs = np.array([99.0, 99.5, 99.7, 99.9]) / 100.0
    for cv in (0.8, 0.9, 1.0):
        from_prod = kritsky_menkel_ppf(probs, 1.0, cv, cv)
        from_table = get_ordinates(1.0, cv)
        idx = [int(np.argmin(np.abs(np.asarray(PROBS) * 100 - p * 100)))
               for p in probs]
        np.testing.assert_allclose(from_prod, np.asarray(from_table)[idx],
                                   rtol=1e-12)
