def test_neighbour_nodes_are_intact() -> None:
    """Точные по печати узлы вокруг исправленных остаются точными.

    Cv = 0,7 верен на всех четырёх глубоких уровнях; при P = 99 % верны
    Cv = 0,8 и Cv = 0,9. Если правка растеклась, эти узлы сдвинутся.
    """
    intact = {
        (99.0, 0.7): 0.015, (99.5, 0.7): 0.008,
        (99.7, 0.7): 0.004, (99.9, 0.7): 0.001,
        (99.0, 0.8): 0.004, (99.0, 0.9): 0.001,
        (99.5, 0.8): 0.002, (99.7, 0.8): 0.001,
    }
    for (p, cv), exp in intact.items():
        got = TABLES[1][cv][_idx(p)]
        assert got == pytest.approx(exp, rel=1e-12, abs=0.0), (
            f"P={p} %, Cv={cv}: {got!r} вместо {exp!r} - соседний узел сдвинут"
        )


