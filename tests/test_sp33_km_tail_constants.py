def test_p001_row_unchanged() -> None:
    """Строка P = 0,001 % сознательно не трогалась.

    Её расхождение с печатью (1-3 %) - вопрос происхождения данных, а не
    признанная ошибка. Тест фиксирует текущие значения: правка хвоста не
    должна их сдвинуть.
    """
    for cv, exp in P001_ROW.items():
        got = TABLES[1][cv][0]
        assert got == pytest.approx(exp, rel=1e-12, abs=0.0), (
            f"TABLES[1][{cv}][P=0.001 %] = {got!r}, было {exp!r}. Строку "
            "P = 0,001 % менять нельзя - отдельный вопрос."
        )


def test_only_the_eight_cells_differ_from_paper_in_the_far_tail() -> None:
    """В углу Cv >= 0,8 / P >= 99 % расходится ровно 8 ячеек."""
    paper = {
        (99.0, 1.0): 0.1e-3,
        (99.5, 0.9): 0.2e-3, (99.5, 1.0): 0.3e-4,
        (99.7, 0.9): 0.9e-4, (99.7, 1.0): 0.1e-4,
        (99.9, 0.8): 0.2e-3, (99.9, 0.9): 0.1e-4, (99.9, 1.0): 0.2e-5,
    }
    mismatched = []
    for p in (99.0, 99.5, 99.7, 99.9):
        for cv in (0.8, 0.9, 1.0):
            got = TABLES[1][cv][_idx(p)]
            exp = paper.get((p, cv), got)
            if abs(got - exp) > 1e-12:
                mismatched.append((p, cv))
    assert not mismatched, f"все ещё расходятся с первоисточником: {mismatched}"


