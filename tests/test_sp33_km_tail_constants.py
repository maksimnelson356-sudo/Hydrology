"""Регрессия на доказанный дефект: хвостовые ординаты КМ по первоисточнику.

ЧТО ЗДЕСЬ ЗАКРЕПЛЕНО.

1. Восемь исправленных констант блока Cs/Cv = 1. Значения взяты с печатного
   скана: Пособие Гидрометеоиздата 1984, Приложение 2, Таблица 3, стр. 126-127.
   Степень десятки в мантиссе существенна и вшита в ожидаемое число:
       0,1*10^-3 = 0.0001    0,2*10^-3 = 0.0002    0,3*10^-4 = 0.00003
       0,9*10^-4 = 0.00009   0,1*10^-4 = 0.00001   0,2*10^-5 = 0.000002
   Последнее - 0.000002, а НЕ 0.00002.

2. Отсутствие ложного обрезания в ноль. Раньше при Cs = Cv сдвиг гаммы
   A0 = -X, нижний хвост уходил в минус и резался np.maximum(., 0) в ровно
   ноль - 33 нормированные ячейки, все из которых в первоисточнике
   положительны. Проверяется по всему блоку, а не в одной точке.

3. Строка P = 0,001 % НЕ менялась. Её расхождение с печатью (1-3 %) -
   отдельный вопрос происхождения данных, ошибкой не признан. Тест
   фиксирует текущие значения, чтобы правка хвоста их не сдвинула.

4. Соседние узлы не задеты: те же 8 ошибок были локальны для угла
   Cv >= 0,8 / P >= 99 %, а строка P = 99 % при Cv = 0,9 и весь блок
   Cv = 0,7 точны и по печати, и по таблице.

5. Монотонность и положительность хвоста: первоисточник убывает по P,
   таблица после правки обязана вести себя так же.
"""

from __future__ import annotations

import numpy as np
import pytest

from core.stats.frequency import kritsky_menkel_ppf
from core.stats.kritsky_tables import PROBS, TABLES, get_ordinates

# Печать: «0,1*10^-3» и т.д. Мантисса и степень десятки - вместе.
FIXED_NODES = [
    (99.0, 1.0, 0.1e-3),
    (99.5, 0.9, 0.2e-3),
    (99.5, 1.0, 0.3e-4),
    (99.7, 0.9, 0.9e-4),
    (99.7, 1.0, 0.1e-4),
    (99.9, 0.8, 0.2e-3),
    (99.9, 0.9, 0.1e-4),
    (99.9, 1.0, 0.2e-5),
]

# Бывшие значения модуля - чтобы правка не откатилась назад.
OLD_VALUES = {
    (99.0, 1.0): 0.0003,
    (99.5, 0.9): 0.0007,
    (99.5, 1.0): 0.0002,
    (99.7, 0.9): 0.0005,
    (99.7, 1.0): 0.0001,
    (99.9, 0.8): 0.0005,
    (99.9, 0.9): 0.0003,
    (99.9, 1.0): 0.00005,
}

# Строка P = 0,001 % - не трогали. Значения до и после правки совпадают.
P001_ROW = {0.8: 4.8102, 0.9: 5.1617, 1.0: 5.4393}

# Нормированные ячейки, которые раньше обрезались в ноль: P -> normative kp.
# [5] 1984, Прил. 2, табл. 3, блок Cs = Cv.
CLIPPED_TO_ZERO = {
    0.4: {99.9: 0.108},
    0.5: {99.5: 0.081, 99.7: 0.062, 99.9: 0.036},
    0.6: {99.0: 0.047, 99.5: 0.028, 99.7: 0.019, 99.9: 0.008},
    0.7: {97.0: 0.048, 99.0: 0.015, 99.5: 0.008, 99.7: 0.004, 99.9: 0.001},
    0.8: {95.0: 0.036, 97.0: 0.018, 99.0: 0.004, 99.5: 0.002, 99.7: 0.001,
           99.9: 0.0002},
    0.9: {90.0: 0.045, 95.0: 0.013, 97.0: 0.005, 99.0: 0.001, 99.5: 0.0002,
           99.7: 0.00009, 99.9: 0.00001},
    1.0: {90.0: 0.019, 95.0: 0.004, 97.0: 0.001, 99.0: 0.0001, 99.5: 0.00003,
           99.7: 0.00001, 99.9: 0.000002},
}


def _idx(p_pct: float) -> int:
    return int(np.argmin(np.abs(np.asarray(PROBS) * 100 - p_pct)))


# --------------------------------------------------------------------------- #
# 1. Восемь исправленных констант
# --------------------------------------------------------------------------- #

@pytest.mark.parametrize(("p_pct", "cv", "expected"), FIXED_NODES)
def test_corrected_node_matches_paper(p_pct: float, cv: float, expected: float) -> None:
    """Табличная константа равна первоисточнику, включая степень десяти."""
    got = TABLES[1][cv][_idx(p_pct)]
    assert got == pytest.approx(expected, rel=1e-12, abs=0.0), (
        f"TABLES[1][{cv}][P={p_pct} %] = {got!r}, в [5] {expected!r}. "
        "Правка хвоста откатилась."
    )


@pytest.mark.parametrize(("p_pct", "cv", "expected"), FIXED_NODES)
def test_old_wrong_value_is_gone(p_pct: float, cv: float, expected: float) -> None:
    """Прежнее (завышенное) значение больше не встречается."""
    got = TABLES[1][cv][_idx(p_pct)]
    old = OLD_VALUES[(p_pct, cv)]
    assert got != pytest.approx(old, rel=1e-12, abs=0.0), (
        f"P={p_pct} %, Cv={cv}: осталось старое значение {old!r}"
    )
    assert expected < old, "первоисточник должен быть ниже прежнего значения"


def test_last_node_is_two_millionths_not_twenty_thousandths() -> None:
    """0,2*10^-5 = 0.000002. Не 0.00002 - в этом суть всей правки."""
    got = TABLES[1][1.0][_idx(99.9)]
    assert got == pytest.approx(0.000002, rel=1e-12, abs=0.0)
    assert got != pytest.approx(0.00002, rel=1e-12, abs=0.0), (
        "Вернулось 0.00002 - потерян множитель 10^-5 при чтении мантиссы."
    )


