"""Сверка кривой Крицкого-Менкеля с тремя опубликованными таблицами ординат.

ИСТОЧНИК ОРИДИНАТ. Сикан А.В., Винокуров И.О., Дрегваль М.С. Учебное пособие
«Гидрологические расчеты». Часть I. РГГМУ, 2021, табл. 11 (стр. 23), табл. 12
(стр. 23), табл. 17 (стр. 29). Загружен пользователем как
«Пособие по определению расчетных гидрологических характеристик. Часть 1.pdf».

Это НЕ нормативное пособие 1984 года ([5] из библиографии СП 33) — то самое
перечислено в литературе учебника под номером 8. Поэтому таблицы здесь служат
опубликованным численным ориентиром, а не подтверждением норматива. Номограмм,
которые требует п. 5.5, в этом файле нет вообще.

ПОЧЕМУ ТАБЛИЦЫ ВСЁ РАВНО ПОЛЕЗНЫ. Все три имеют Cs/Cv = 1, то есть лежат в
области Крицкого-Менкеля (Cs/Cv < 2) — ровно там, где поправка (5.7) теперь не
применяется. Это независимая численная проверка кривой, которой раньше не было.

ЧТО ЗАКРЕПЛЯЮТ ЭТИ ТЕСТЫ, А ЧТО — НЕТ.

Закрепляется (проходит сейчас, должно остаться):
  - тело кривой P = 5...95 % совпадает с публикацией в пределах 0,016;
  - kp при P = 50 % меньше единицы (0,97) — характерная черта биномиальной
    кривой, а не опечатка; наша кривая это воспроизводит.

НЕ закрепляется как «правильный» результат и проверяется явно как ИЗВЕСТНЫЙ
ПРОБЕЛ: хвосты P < 1 % и P > 99 %. Расхождение там систематическое и одного
знака во всех трёх независимых таблицах. Причина установлена: при Cs = Cv сдвиг
гаммы A0 = X*(1 - 2*Cv/Cs) = -X, то есть распределение допускает отрицательные
расходы, и код режет их в ноль. При P = 99,9 % наша кривая даёт ровно 0, тогда
как в пособии 0,09...0,14.

Эти тесты намеренно падают, если разрыв в хвостах вдруг исчезнет: значит его
закрыли подгонкой по этим же таблицам, и такое «исправление» надо отклонить.
Правильное исправление — по первоисточнику (рекуррентная формула биномиальной
кривой), а не по учебнику 2021 года.
"""

from __future__ import annotations

import json
import pathlib

import numpy as np
import pytest

from core.stats.frequency import kritsky_menkel_ppf

FIXTURE = pathlib.Path(__file__).parent / "fixtures" / "sp33_km_published_ordinates_v1.json"

P_PERCENT = [0.1, 1, 5, 10, 25, 50, 75, 90, 95, 99, 99.9]
CASES = {"Cv=0.38": 0.38, "Cv=0.40": 0.40, "Cv=0.43": 0.43}

# Границы областей. В центре расхождение не превышает 0,016 (проверено).
CENTRAL_PROBS = [5, 10, 25, 50, 75, 90, 95]
CENTRAL_TOL = 0.02


@pytest.fixture(scope="module")
def published() -> dict:
    return json.loads(FIXTURE.read_text(encoding="utf-8"))


def _ref(published: dict, label: str) -> dict[float, float]:
    """Публикационные kp в виде {P, %: kp}.

    Именно словарь, а не позиционный список. Списком здесь легко сдвинуть
    соответствие на единицу и сравнивать kp(5 %) с публикационным kp(0,1 %) —
    тест при этом проходит, проверяя не то.
    """
    probs = published["probabilities_percent"]
    return dict(zip(probs, published["published_kp"][label], strict=True))


def _kp(cv: float, probs_percent: list[float]) -> np.ndarray:
    return kritsky_menkel_ppf(
        np.array(probs_percent, dtype=float) / 100.0, 1.0, cv, cv
    )


@pytest.mark.parametrize("label", list(CASES))
def test_body_matches_published(published: dict, label: str) -> None:
    """Тело кривой P = 5...95 % совпадает с публикацией.

    Три независимые таблицы, три разных Cv, одно и то же отклонение по модулю —
    это не совпадение и не округление.
    """
    cv = CASES[label]
    ref = _ref(published, label)
    kp = _kp(cv, CENTRAL_PROBS)

    for p, got in zip(CENTRAL_PROBS, kp, strict=True):
        exp = ref[p]
        assert abs(got - exp) <= CENTRAL_TOL, (
            f"{label}: kp({p} %) = {got:.3f}, в пособии {exp:.2f} — "
            f"расхождение {abs(got - exp):.3f} превышает {CENTRAL_TOL}. "
            "Тело кривой разошлось с публикацией, это надо разбирать."
        )


@pytest.mark.parametrize("label", list(CASES))
def test_median_is_below_mean(published: dict, label: str) -> None:
    """Характерная черта: kp(50 %) = 0,97, а не 1,00.

    Медиана биномиальной кривой лежит чуть ниже среднего. Если кривая станет
    строго симметричной в этой точке, значит она перестала быть кривой
    Крицкого-Менкеля.
    """
    cv = CASES[label]
    kp50 = float(kritsky_menkel_ppf(np.array([0.5]), 1.0, cv, cv)[0])
    assert kp50 < 1.0, "медиана обязана лежать ниже среднего"
    assert abs(kp50 - 0.97) <= 0.02, f"kp(50 %) = {kp50:.3f}, ожидалось около 0,97"


@pytest.mark.parametrize("label", list(CASES))
def test_known_tail_gap_is_still_there(published: dict, label: str) -> None:
    """ИЗВЕСТНЫЙ ПРОБЕЛ: хвосты расходятся с публикацией.

    Тест фиксирует РАСХОЖДЕНИЕ, а не верное значение. Его задача — не дать
    пробелу исчезнуть незаметно и не дать закрыть его подгонкой по учебнику 2021
    года вместо первоисточника.

    Утверждается ровно наблюдаемый механизм: результат равен обрезке в ноль
    отрицательного квантиля, то есть max(сырой квантиль, 0). Проверять именно
    max(), а не «ноль», нельзя: обрезаются не все случаи (при Cv = 0,38 сырой
    квантиль положителен и равен 0,0273).
    """
    from scipy import stats

    cv = CASES[label]
    ref = _ref(published, label)
    kp = _kp(cv, [0.1, 99.9])

    # Сырой квантиль нижнего хвоста P = 99,9 % по той же формуле, что и в коде.
    alpha = 4.0 / cv ** 2
    beta = cv * cv / 2.0
    raw_low = -1.0 + beta * stats.gamma.ppf(0.001, a=alpha, scale=1.0)
    assert kp[1] == pytest.approx(max(raw_low, 0.0), abs=1e-9), (
        f"{label}: kp(99,9 %) = {kp[1]:.4f}, а обрезка даёт {max(raw_low, 0.0):.4f}. "
        "Механизм изменился - разберитесь, что именно поменяли."
    )

    # Пробел: наш нижний хвост занижен относительно публикации в разы.
    assert kp[1] < ref[99.9] - 0.06, (
        f"{label}: kp(99,9 %) = {kp[1]:.4f} против публикационных {ref[99.9]:.2f}. "
        "Пробел в нижнем хвосте пропадает - закройте его по первоисточнику, а не "
        "подгонкой по учебнику 2021 года."
    )

    # Верхний хвост: наша кривая систематически выше публикации.
    assert kp[0] > ref[0.1] + 0.03, (
        f"{label}: kp(0,1 %) = {kp[0]:.3f} против публикационных {ref[0.1]:.2f}. "
        "Расхождение в верхнем хвосте пропало - разберитесь, что изменилось."
    )


def test_clipping_is_not_universal() -> None:
    """Обрезка в ноль действует не во всех случаях - и это тоже проверено.

    При Cv = 0,38 сырой квантиль на P = 99,9 % положителен, поэтому ноль там
    не появляется. Тест защищает формулировку «обрезается в ноль» от того,
    чтобы её повторили как общее свойство кривой.
    """
    from scipy import stats

    raw = {}
    for cv in CASES.values():
        alpha = 4.0 / cv ** 2
        beta = cv * cv / 2.0
        raw[cv] = -1.0 + beta * stats.gamma.ppf(0.001, a=alpha, scale=1.0)

    clipped = {cv for cv, r in raw.items() if r < 0.0}
    assert clipped == {0.40, 0.43}, (
        f"обрезаются {clipped}, а расчёт даёт {raw}. Список обрезаемых случаев "
        "изменился - перепроверь выводы."
    )
    assert raw[0.38] > 0.0
    assert float(_kp(0.38, [99.9])[0]) == pytest.approx(raw[0.38], abs=1e-9)


def test_root_cause_is_negative_shift() -> None:
    """Названная причина расхождения обязана оставаться названной.

    При Cs = Cv сдвиг A0 = X*(1 - 2*Cv/Cs) = -X: трёхпараметрическое гамма в
    этой параметризации допускает отрицательные значения, и код режет их
    функцией np.maximum(., 0). Пока это так, хвосты останутся гауссовскими.
    """
    for cv in CASES.values():
        alpha = 4.0 / cv ** 2
        beta = 1.0 * cv * cv / 2.0
        shift = 1.0 * (1.0 - 2.0 * cv / cv)
        assert alpha > 0
        assert beta > 0
        assert shift == pytest.approx(-1.0), (
            f"Cv={cv}: сдвиг гаммы {shift}, ожидался -1 при Cs = Cv"
        )

    # При P = 99,9 % сырой квантиль действительно отрицателен.
    from scipy import stats

    raw = -1.0 + 0.40 ** 2 / 2.0 * stats.gamma.ppf(
        0.001, a=4.0 / 0.40 ** 2, scale=1.0
    )
    assert raw < 0.0, f"сырой квантиль {raw:.4f}, а он обрезается в ноль np.maximum"


def test_fixture_records_provenance_honestly() -> None:
    """Провенанс обязан быть указан, иначе учебник 2021 года выдадут за [5]."""
    data = json.loads(FIXTURE.read_text(encoding="utf-8"))
    meta = data["_meta"]

    assert "НЕ НОРМАТИВНЫЙ ИСТОЧНИК" in meta["normativity"], (
        "в фикстуре должно быть сказано, что источник не нормативный"
    )
    assert "РГГМУ" in meta["provenance"]
    assert "2021" in meta["provenance"]
    assert "1984" in meta["normativity"], (
        "надо явно отличать учебник 2021 г. от пособия Гидрометеоиздата 1984 г."
    )

    # Все три таблицы обязаны относиться к области Крицкого-Менкеля.
    assert "Cs/Cv = 1" in meta["why_still_useful"]

    # Ключи таблиц и значений обязаны совпадать между собой.
    assert set(data["published_kp"]) == set(data["measured_delta_ours_minus_published"])
    for label, values in data["published_kp"].items():
        assert len(values) == len(data["probabilities_percent"]), (
            f"{label}: {len(values)} ординат на {len(data['probabilities_percent'])} "
            "обеспеченностей - соответствие потеряно"
        )

    # Таблицы 12 и 18 учебника имеют одинаковый Cv = 0,38, значит ординаты
    # обязаны совпасть. Это внутренняя проверка на перепутанные строки.
    assert data["published_kp"]["Cv=0.38"] == [2.33, 1.98, 1.66, 1.51, 1.25, 0.97,
                                               0.72, 0.52, 0.42, 0.26, 0.14]
