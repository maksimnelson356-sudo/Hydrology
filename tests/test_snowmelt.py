# 5. Физически ожидаемые численные значения
# ----------------------------------------------------------------------
@pytest.mark.parametrize(
    "W, P, T_air, A, days, exp_melt, exp_runoff, exp_W_end, note",
    [
        # M = min(A·max(T,0)·days, W); runoff = M + 0.3P; W_end = W - M + 0.7P
        pytest.param(
            120.0, 0.0, 8.0, 3.5, 30, 120.0, 120.0, 0.0,
            "без осадков: сток равен полному таянию", id="melt_only",
        ),
        pytest.param(
            120.0, 25.0, 8.0, 3.5, 30, 120.0, 127.5, 17.5,
            "A·T·d = 840 > W, таяние ограничено запасом", id="melt_capped_by_snow",
        ),
        pytest.param(
            300.0, 25.0, 4.0, 3.5, 30, 300.0, 307.5, 17.5,
            "A·T·d = 420 > W", id="melt_capped_large_snow",
        ),
        pytest.param(
            300.0, 25.0, 2.0, 3.5, 30, 210.0, 217.5, 107.5,
            "A·T·d = 210 < W, таяние не ограничено", id="melt_uncapped",
        ),
        pytest.param(
            200.0, 40.0, 1.0, 3.5, 30, 105.0, 117.0, 123.0,
            "излишек осадков идёт и в сток, и в запас", id="rain_dominant",
        ),
        pytest.param(
            50.0, 25.0, 8.0, 10.0, 30, 50.0, 57.5, 17.5,
            "сильный коэффициент таяния, малый запас", id="strong_coefficient",
        ),
    ],
)
def test_physically_expected_values(
    W, P, T_air, A, days, exp_melt, exp_runoff, exp_W_end, note
) -> None:
    """Численные значения, выведенные арифметически, а не вызовом production.

    Для каждого набора ожидания получены по формулам баланса:
        M       = min(A · max(T_air, 0) · days, W)
        runoff  = M + 0.3 · P
        W_end   = W - M + 0.7 · P
    Оба слагаемых проверяются: и физическая величина, и запас, — чтобы
    ошибка в любом из них не могла остаться незамеченной.
    """
    result = snowmelt_balance(W, P, T_air, A=A, days=days)

    assert result["melt_total_mm"] == pytest.approx(exp_melt), note
    assert result["runoff_total_mm"] == pytest.approx(exp_runoff), (
        f"{note}: сток должен равняться таянию плюс доля осадков"
    )
    assert result["W_final_mm"] == pytest.approx(exp_W_end), note
    assert result["precipitation_mm"] == pytest.approx(P)


# ----------------------------------------------------------------------
# 6. Отсутствие перерасчёта: осадки возвращаются без искажения
# ----------------------------------------------------------------------
def test_precipitation_is_echoed_unchanged() -> None:
    """Поле precipitation_mm возвращает вход без изменения.

    Мелкая, но реально ловимая регрессия: при правке раскладки осадков поле
    легко начинает отдавать P_runoff или P_storage вместо P.
    """
    for P in (0.0, 25.0, 137.5):
        assert snowmelt_balance(120.0, P, 8.0)["precipitation_mm"] == pytest.approx(P)
